#include <iostream>

using namespace std;

int main() {
    int m, n;

    cout << "Введіть m: ";
    cin >> m;
    cout << "Введіть n: ";
    cin >> n;

    int m0 = m, n0 = n;  // зберігаємо початкові значення

    // ---------- Вираз 1: m + --n ----------
    // Спочатку n зменшується на 1, потім додається до m
    m = m0; n = n0;
    int res1 = m + --n;
    cout << "1) m+--n: результат = " << res1
         << ", m = " << m << ", n = " << n << endl;

    // ---------- Вираз 2: m++ < ++n ----------
    // Порівнюється старе m з новим n, після чого m збільшується
    m = m0; n = n0;
    bool res2 = m++ < ++n;
    cout << "2) m++<++n: результат = " << res2
         << ", m = " << m << ", n = " << n << endl;

    // ---------- Вираз 3: n-- < --m ----------
    // Порівнюється старе n з новим m, після чого n зменшується
    m = m0; n = n0;
    bool res3 = n-- < --m;
    cout << "3) n--<--m: результат = " << res3
         << ", m = " << m << ", n = " << n << endl;

    return 0;
}