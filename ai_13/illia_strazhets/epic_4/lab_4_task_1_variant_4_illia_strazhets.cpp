#include <iostream>
#include <cstdlib>
#include <ctime>
#include <cmath>
using namespace std;

// Безпечне зчитування цілого числа з перевіркою коректності вводу (cin.fail())
bool readNumber(int &value)
{
    cin >> value;
    if (cin.fail())
    {
        // Скидаємо прапорець помилки та очищаємо некоректний ввід до кінця рядка
        cin.clear();
        cin.ignore(10000, '\n');
        return false;
    }
    return true;
}

// Головна функція: формування, обробка та друк масиву
int main()
{
    srand(static_cast<unsigned int>(time(nullptr)));

    // 1) Організація статичного масиву з псевдозмінними межами
    const int N = 100; // максимально можлива довжина
    int a[N];          // статичний масив
    int real_size;     // реальна довжина масиву, з якою працює користувач

    cout << "Введіть початкову кількість елементів (не більше " << N / 2 << "): ";
    // Перевірка коректності введеного розміру (нечислові символи та межі)
    if (!readNumber(real_size) || real_size <= 0 || real_size > N / 2)
    {
        cout << "Некоректний розмір! Введіть ціле число від 1 до " << N / 2 << ".\n";
        return 1;
    }

    // Заповнення масиву випадковими числами від -20 до 20
    for (int i = 0; i < real_size; ++i)
    {
        a[i] = rand() % 41 - 20;
    }

    // 2) Друк початкового масиву
    cout << "\nПочатковий масив (" << real_size << " елементів):\n";
    for (int i = 0; i < real_size; ++i)
    {
        cout << a[i] << " ";
    }
    cout << "\n\n";

    // 3) Знищення елементів, індекси яких кратні 3 (0, 3, 6, 9...)
    int write_idx = 0;
    for (int read_idx = 0; read_idx < real_size; ++read_idx)
    {
        if (read_idx % 3 != 0)
        {
            a[write_idx] = a[read_idx];
            write_idx++;
        }
    }
    // Зменшення реальної довжини масиву
    real_size = write_idx;

    cout << "Масив після видалення (індекси кратні 3) (" << real_size << " елементів):\n";
    for (int i = 0; i < real_size; ++i)
    {
        cout << a[i] << " ";
    }
    cout << "\n\n";

    // 4) Додавання після кожного від’ємного елемента значення |a[i-1] + 1|
    for (int i = 0; i < real_size; ++i)
    {
        if (a[i] < 0 && real_size < N)
        {
            // Безпечне отримання значення a[i-1] (для першого елемента беремо 0)
            int prev_val = (i > 0) ? a[i - 1] : 0;
            int new_val = abs(prev_val + 1);

            // Зсув елементів праворуч для звільнення місця під новий елемент
            for (int j = real_size; j > i + 1; --j)
            {
                a[j] = a[j - 1];
            }

            // Вставка нового значення
            a[i + 1] = new_val;

            // Збільшення реальної довжини масиву
            real_size++;

            // Пропускаємо щойно доданий елемент
            i++;
        }
    }

    // 5) Друк отриманого масиву
    cout << "Масив після вставки елементів (" << real_size << " елементів):\n";
    for (int i = 0; i < real_size; ++i)
    {
        cout << a[i] << " ";
    }
    cout << "\n";

    return 0;
}