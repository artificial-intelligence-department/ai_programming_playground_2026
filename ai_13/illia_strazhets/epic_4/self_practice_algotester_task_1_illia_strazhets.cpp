#include <iostream>
#include <iomanip>
using namespace std;

// Головна функція: зчитування категорій і покупок, вибір 2 найвигідніших категорій
int main()
{
    string names[6];           // Назви 6 категорій кешбеку, які пропонує банк
    long long percent[6];      // Відсоток кешбеку для кожної категорії
    long long earned[6] = {0}; // Накопичений кешбек по кожній категорії (у копійках, щоб уникнути похибки double)

    // Зчитуємо 6 банківських категорій та їхні відсотки
    for (int i = 0; i < 6; i++)
    {
        cin >> names[i] >> percent[i];
    }

    int n; // Кількість запланованих покупок
    cin >> n;

    // Обробляємо кожну покупку
    for (int i = 0; i < n; i++)
    {
        string cat;      // Категорія поточної покупки
        long long spend; // Сума покупки в гривнях
        cin >> cat >> spend;

        // Шукаємо, чи є ця категорія серед 6 доступних у банку
        for (int j = 0; j < 6; j++)
        {
            if (cat == names[j])
            {
                // Додаємо кешбек у копійках (гривні * відсоток) до відповідної категорії
                earned[j] += spend * percent[j];
                break; // Категорію знайдено, далі шукати не потрібно
            }
        }
    }

    // Сортуємо масив із 6 категорій за спаданням (від найбільшого кешбеку до найменшого)
    for (int i = 0; i < 6; i++)
    {
        for (int j = 0; j < 6 - i - 1; j++)
        {
            if (earned[j] < earned[j + 1])
            {
                long long temp = earned[j];
                earned[j] = earned[j + 1];
                earned[j + 1] = temp;
            }
        }
    }

    // Сумуємо 2 найбільші категорії, переводимо з копійок у гривні (/ 100.0) і виводимо з 2 знаками після коми
    cout << fixed << setprecision(2) << (earned[0] + earned[1]) / 100.0;
    return 0;
}