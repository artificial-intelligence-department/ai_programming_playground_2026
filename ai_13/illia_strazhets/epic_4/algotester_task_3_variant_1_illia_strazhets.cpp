#include <iostream>
#include <string>

using namespace std;

// Головна функція: зчитує закляття і рахує мінімальну кількість ритуалів
int main()
{
    int N;       // кількість рядків закляття
    string word; // поточне слово закляття

    // Зчитуємо кількість рядків; якщо ввід некоректний — завершуємо роботу
    if (!(cin >> N))
    {
        return 0;
    }
    int count = 0; // кількість потрібних ритуалів

    // Читаємо слова до кінця вводу: межі рядків не важливі, бо слова розділені
    // пробілами, а блок '#' не може переходити з одного слова в інше
    while (cin >> word)
    {
        for (size_t c = 0; c < word.length(); c++)
        {
            // Рахуємо ритуал тільки на початку нового блоку з '#'
            if (word[c] == '#' && (c == 0 || word[c - 1] != '#'))
            {
                count++;
            }
        }
    }

    // Один ритуал зцілює весь неперервний блок '#', тому відповідь — кількість блоків
    cout << count << endl;
    return 0;
}