#include <iostream>
using namespace std;

// Переворот доміношки: обмін лівої та правої половини через параметри-посилання
void flip(int &x, int &y)
{
    int temp = x;
    x = y;
    y = temp;
}

// Жадібна перевірка ланцюжка: a[i] — ліва половина i-тої доміношки, b[i] — права.
// Орієнтація першої доміношки вже зафіксована, тому кожна наступна має
// не більше одного правильного положення — його й підбираємо.
bool checkChain(int *a, int *b, int n)
{
    // Порівнюємо праву половину поточної доміношки з лівою половиною наступної
    for (int i = 0; i < n - 1; i++)
    {
        if (b[i] != a[i + 1])
        {
            flip(a[i + 1], b[i + 1]); // Перевертаємо НАСТУПНЕ доміно, а не поточне
        }
        if (b[i] != a[i + 1])
        {
            return false; // Якщо і після перевороту не зійшлося — одразу false
        }
    }
    return true;
}

// Головна функція: зчитування доміношок і перевірка двох варіантів старту
int main()
{
    int n; // кількість доміношок
    cin >> n;

    // Динамічні масиви половин доміношок розміром n
    int *a = new int[n];
    int *b = new int[n];
    // Копії для другого варіанту (якщо 0-ве доміно треба перевернути на старті)
    int *a2 = new int[n];
    int *b2 = new int[n];

    // Зчитуємо половини кожної доміношки та одразу робимо копію
    for (int i = 0; i < n; i++)
    {
        cin >> a[i] >> b[i];
        a2[i] = a[i];
        b2[i] = b[i];
    }

    flip(a2[0], b2[0]); // У другому варіанті перевертаємо 0-ве доміно

    // Ряд можна викласти, якщо підходить хоча б один із двох варіантів старту
    if (checkChain(a, b, n) || checkChain(a2, b2, n))
        cout << "TAK";
    else
        cout << "NI";

    // Звільняємо всю динамічну пам'ять
    delete[] a;
    delete[] b;
    delete[] a2;
    delete[] b2;
    return 0;
}