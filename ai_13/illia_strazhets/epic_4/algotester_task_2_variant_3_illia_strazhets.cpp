/*
Algotester Lab 2. Варіант 3.
Задача: два дрони стартують з першої та останньої клітинки масиву й одночасно
летять назустріч один одному. На кожному ході швидкість дрона дорівнює
значенню клітинки, у якій він стоїть. Потрібно вивести фінальні позиції
дронів і одну з подій: Collision, Miss або Stopped.
Автор: Illia Strazhets
Група: AI-13
*/
#include <iostream>
using namespace std;

// Головна функція: зчитування масиву та покрокова симуляція польоту дронів
int main()
{
    const int N = 1000; // максимальний розмір масиву за умовою (1 ≤ N ≤ 1000)
    int pos1, pos2, n;  // pos1 — позиція лівого дрона, pos2 — правого (індекси з 0)
    int a[N] = {};      // значення клітинок (швидкості дронів)

    // Зчитуємо розмір масиву; некоректний розмір — завершуємо роботу
    cin >> n;
    if (n <= 0 || n > N)
    {
        return 0;
    }

    // Зчитуємо значення клітинок з перевіркою меж за умовою: 1 ≤ a[i] ≤ 5
    // (нульова швидкість заборонена — дрон стояв би на місці вічно)
    for (int i = 0; i < n; ++i)
    {
        cin >> a[i];
        if (a[i] < 1 || a[i] > 5)
        {
            return 0;
        }
    }

    // Лівий дрон стартує з першої клітинки, правий — з останньої
    pos1 = 0;
    pos2 = n - 1;

    // Симуляція: перед кожним ходом (і ще до зльоту) перевіряємо три події
    while (true)
    {
        // Лівий дрон опинився правіше за правого — промах
        if (pos1 > pos2)
        {
            // +1 — переходимо до нумерації клітинок з 1, як в умові
            cout << pos1 + 1 << " " << pos2 + 1 << endl;
            cout << "Miss" << endl;
            break;
        }
        // Обидва дрони в одній клітинці — зіткнення
        if (pos1 == pos2)
        {
            cout << pos1 + 1 << " " << pos2 + 1 << endl;
            cout << "Collision" << endl;
            break;
        }
        // Дрони в сусідніх клітинках, один навпроти одного — зупинка
        if (pos2 - pos1 == 1)
        {
            cout << pos1 + 1 << " " << pos2 + 1 << endl;
            cout << "Stopped" << endl;
            break;
        }
        // Хід: лівий летить праворуч, правий — ліворуч на значення своєї клітинки
        pos1 += a[pos1];
        pos2 -= a[pos2];
    }
    return 0;
}
