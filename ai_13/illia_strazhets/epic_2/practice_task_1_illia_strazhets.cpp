#include <iostream>
using namespace std;
int main()
{
    // Введення змінних для параметрів пароля
    int length;
    char hasDigits;
    char hasLetters;
    char hasSpecialChars;
    int sum_symbols;
    char level;
    string levelName;

    // Введення параметрів пароля користувачем
    cout << "Довжина пароля: ";
    cin >> length;
    if (length < 1 || length > 64) // Перевірка на правильність введення
    {
        cout << "Помилка: Довжина пароля повинна бути в межах від 1 до 64 символів." << endl;
        return 1; // Завершення програми з кодом помилки
    }

    cout << "Чи є цифри (y/n): ";
    cin >> hasDigits;
    if (!(hasDigits == 'y' || hasDigits == 'n')) // Перевірка на правильність введення
    {
        cout << "Помилка: Введіть 'y' або 'n'." << endl;
        return 1; // Завершення програми з кодом помилки
    }

    cout << "Чи є великі літери (y/n): ";
    cin >> hasLetters;
    if (!(hasLetters == 'y' || hasLetters == 'n')) // Перевірка на правильність введення
    {
        cout << "Помилка: Введіть 'y' або 'n'." << endl;
        return 1; // Завершення програми з кодом помилки
    }

    cout << "Чи є спеціальні символи (y/n): ";
    cin >> hasSpecialChars;
    cout << endl;
    if (!(hasSpecialChars == 'y' || hasSpecialChars == 'n')) // Перевірка на правильність введення
    {
        cout << "Помилка: Введіть 'y' або 'n'." << endl;
        return 1; // Завершення програми з кодом помилки
    }

    // Мінімальні вимоги: Пароль повинен мати довжину не менше 8 символів і містити принаймні 2 з наступних типів символів: цифри, великі літери, спеціальні символи
    // Підрахунок кількості типів символів, які відповідають вимогам
    sum_symbols = (hasDigits == 'y') + (hasLetters == 'y') + (hasSpecialChars == 'y'); // == перетворює true/false в 1/0, тому сума дає кількість типів символів

    if (length >= 8 && sum_symbols >= 2) // Перевірка мінімальних вимог
    {
        cout << "Мінімальні вимоги: ПРОЙДЕНО" << endl;
    }
    else
    {
        cout << "Мінімальні вимоги: НЕ ПРОЙДЕНО" << endl;
    }

    // Рівень надійності від 1 до 5, де 1 - дуже слабкий, а 5 - дуже надійний
    if (length < 6)
    {
        level = 1;
        levelName = "Дуже слабкий";
    }
    else if (length < 8 || sum_symbols == 0)
    {
        level = 2;
        levelName = "Слабкий";
    }
    else if (sum_symbols == 1)
    {
        level = 3;
        levelName = "Середній";
    }
    else if (length >= 12 && sum_symbols == 3)
    {
        level = 5;
        levelName = "Дуже надійний";
    }
    else
    {
        level = 4;
        levelName = "Надійний";
    }
    cout << "Рівень надійності: " << (int)level << " - " << levelName << endl;

    // Надання рекомендацій щодо покращення надійності пароля
    switch (level)
    {
    case 1:
        cout << "Рекомендація: Пароль надто короткий. Мінімум 8 символів." << endl;
        break;
    case 2:
        cout << "Рекомендація: Збільште довжину до 8+ символів і додайте цифри, великі літери або спеціальні символи." << endl;
        break;
    case 3:
        cout << "Рекомендація: Додайте ще один тип символів або збільште довжину до 12." << endl;
        break;
    case 4:
        cout << "Рекомендація: Хороший пароль. Для максимуму 12+ символів і всі три типи символів." << endl;
        break;
    case 5:
        cout << "Рекомендація: Відмінно. Змінювати нічого не потрібно." << endl;
        break;
    default:
        break;
    }

    // Додаткове попередження (якщо пароль складається тільки з літер)
    if (hasDigits == 'n' && hasSpecialChars == 'n')
    {
        cout << "Попередження: пароль тільки з літер підбирається швидше." << endl;
    }
    return 0; // Завершення програми без помилок
}