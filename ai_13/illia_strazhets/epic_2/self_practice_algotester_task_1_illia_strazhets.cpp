#include <iostream>
using namespace std;

int main()
{
    // Оголошення 64-бітних цілих змінних для розмірів шоколадки (n, m) та числа k.
    long long n, m, k;

    // Конструкція if (!(cin >> ...)) захищає від збою при читанні (наприклад, якщо вхідний файл порожній).
    if (!(cin >> n >> m >> k))
        return 0;

    // Перевірка: чи ділиться загальна кількість часточок (n * m) на k без залишку.
    if ((n * m) % k == 0)
    {
        cout << "YES"; // Якщо ділиться порівну — виводимо YES
    }
    else
    {
        cout << "NO"; // Якщо порівну поділити неможливо — виводимо NO
    }

    return 0;
}