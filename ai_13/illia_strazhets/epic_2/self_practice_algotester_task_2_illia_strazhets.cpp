#include <iostream>
#include <cmath>

using namespace std;

int main()
{
    const long long n = 13;     // Всього 13 чаювань щогодини: з 9:00 ранку до 21:00 вечора включно
    const long long hours = 12; // 12 інтервалів між 13 чаюваннями (n - 1 = 12)

    long long a, b; // 64-бітні цілі змінні, оскільки значення об'ємів досягають 10^9

    // Зчитуємо a (об'єм о 9:00) та b (об'єм о 21:00); якщо ввід порожній, завершуємо програму
    if (!(cin >> a >> b))
        return 0;

    // Різниця об'ємів повинна рівномірно ділитися на 12 кроків.
    // abs() бере модуль, щоб уникнути проблем із залишком від від'ємного числа при a < b.
    if (abs(a - b) % hours != 0)
    {
        cout << -1; // Цілочисельної прогресії не існує — виводимо -1
        return 0;
    }

    // Сума арифметичної прогресії: S = (перший + останній) * кількість / 2.
    long long sum = (a + b) * n / 2;

    cout << sum; // Виводимо сумарний об'єм чаю за день

    return 0;
}