#include <iostream>
using namespace std;

const int N = 100;   // статичний масив великої довжини
int a[N];
int n;               // реальна довжина кільця (n <= N)

// друк по кільцю вліво: від K-ого елемента, увесь круг (K, K-1, ..., 1, n, ..., K+1)
void printLeft(int k){
    int i = k - 1;                 // K нумеруємо з 1
    for (int j = 0; j < n; j++) {
        cout << a[i] << " ";
        i = (i - 1 + n) % n;       // крок вліво; від першого переходимо до останнього
    }
    cout << endl;
}

// друк по кільцю вправо: від K-ого елемента, увесь круг (K, K+1, ..., n, 1, ..., K-1)
void printRight(int k){
    int i = k - 1;
    for (int c = 0; c < n; c++) {
        cout << a[i] << " ";
        i = (i + 1) % n;           // крок вправо; від останнього переходимо до першого
    }
    cout << endl;
}

// додати елемент на початок кільця
void addFirst(int x){
    for (int i = n; i > 0; i--)
        a[i] = a[i - 1];
    a[0] = x;
    n++;                           // збільшуємо реальну довжину
}

// додати елемент в кінець кільця
void addLast(int x){
    a[n] = x;
    n++;
}

int main(){
    int k, x;

    cout << "Кількість елементів кільця (1.." << N - 2 << "): ";
    cin >> n;
    if (n < 1 || n > N - 2) {
        cout << "Некоректна довжина" << endl;
        return 1;
    }

    cout << "Введіть " << n << " елементів:" << endl;
    for (int i = 0; i < n; i++)
        cin >> a[i];

    cout << "Введіть K (1.." << n << "): ";
    cin >> k;
    if (k < 1 || k > n) {
        cout << "Некоректне K" << endl;
        return 1;
    }

    // 2) друк від K-ого по кільцю вліво
    cout << "\nКільце від K-ого елемента вліво:" << endl;
    printLeft(k);

    // 3) додати в кільце перший і останній елементи
    cout << "\nНовий перший елемент: ";
    cin >> x;
    addFirst(x);
    cout << "Новий останній елемент: ";
    cin >> x;
    addLast(x);

    // 4) друк від K-ого по кільцю вправо
    cout << "\nКільце від K-ого елемента вправо:" << endl;
    printRight(k);

    return 0;
}