#include <iostream>

using namespace std;

int main(){
    // Зчитуємо кількість подач
    int n;
    cin >> n;

    // Зчитуємо результати всіх подач
    // K — виграв Коля, V — виграв Вася
    string s;
    cin >> s;

    // Кількість виграних партій Колі та Васі
    int kolyaGames = 0;
    int vasyaGames = 0;

    // Очки в поточній партії
    int kolya = 0;
    int vasya = 0;

    // Перебираємо всі подачі
    for (int i = 0; i < n; i++){
        // Якщо подачу виграв Коля — додаємо йому очко
        if (s[i] == 'K')
            kolya++;
        else
            // Інакше очко отримує Вася
            vasya++;

        // Перевіряємо, чи закінчилася поточна партія
        // Хтось повинен мати мінімум 11 очок
        // і перевагу мінімум у 2 очки
        if ((kolya >= 11 || vasya >= 11) && abs(kolya - vasya) >= 2){
            // Визначаємо переможця партії
            if (kolya > vasya)
                kolyaGames++;
            else
                vasyaGames++;

            // Обнуляємо очки для початку нової партії
            kolya = 0;
            vasya = 0;
        }
    }

    // Виводимо загальний рахунок по виграних партіях
    cout << kolyaGames << ":" << vasyaGames << endl;

    // Якщо після всіх подач залишилися очки,
    // значить останню партію не дограли
    if (kolya != 0 || vasya != 0){
        // Виводимо рахунок незавершеної партії
        cout << kolya << ":" << vasya << endl;
    }

    return 0;
}