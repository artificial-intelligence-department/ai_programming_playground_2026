#include <iostream>
#include <string>

using namespace std;

int main()
{
    // Характеристики пароля, які введе користувач.
    int length;
    string hasDigits;
    string hasUppercase;
    string hasSpecial;

    // Зчитуємо довжину пароля в символах і перевіряємо допустимі межі.
    cout << "Довжина пароля: ";
    if (!(cin >> length) || length < 1 || length > 64)
    {
        cout << "Помилка: довжина мусить бути від 1 до 64. Введіть дійсне значення.\n";
        return 1;
    }

    // З'ясовуємо, чи містить пароль цифри; приймаємо рівно y або n.
    cout << "Чи є цифри (y/n): ";
    if (!(cin >> hasDigits) || (hasDigits != "y" && hasDigits != "n"))
    {
        cout << "Помилка: введіть рівно y або n.\n";
        return 1;
    }

    // З'ясовуємо, чи містить пароль великі літери; приймаємо рівно y або n.
    cout << "Чи є великі літери (y/n): ";
    if (!(cin >> hasUppercase) || (hasUppercase != "y" && hasUppercase != "n"))
    {
        cout << "Помилка: введіть рівно y або n.\n";
        return 1;
    }

    // З'ясовуємо, чи містить пароль спеціальні символи; приймаємо рівно y або n.
    cout << "Чи є спеціальні символи (y/n): ";
    if (!(cin >> hasSpecial) || (hasSpecial != "y" && hasSpecial != "n"))
    {
        cout << "Помилка: введіть рівно y або n.\n";
        return 1;
    }

    // Рахуємо кількість наявних типів серед цифр, великих літер і спеціальних символів.
    int typeCount = 0;

    if (hasDigits == "y")
    {
        typeCount++;
    }

    if (hasUppercase == "y")
    {
        typeCount++;
    }

    if (hasSpecial == "y")
    {
        typeCount++;
    }

    // Для мінімальних вимог потрібні щонайменше 8 символів і 2 типи.
    cout << "\nМінімальні вимоги: ";

    if (length >= 8 && typeCount >= 2)
    {
        cout << "ПРОЙДЕНО\n";
    }
    else
    {
        cout << "НЕ ПРОЙДЕНО\n";
    }

    // Перевіряємо правила за порядком: перше виконане визначає рівень.
    int level;

    if (length < 6)
    {
        level = 1;
    }
    else if (length < 8 || typeCount == 0)
    {
        level = 2;
    }
    else if (typeCount == 1)
    {
        level = 3;
    }
    else if (length >= 12 && typeCount == 3)
    {
        level = 5;
    }
    else
    {
        level = 4;
    }

    // Виводимо назву визначеного рівня та рекомендацію з умови задачі.
    switch (level)
    {
        case 1:
            cout << "Рівень надійності: 1 - Дуже слабкий\n";
            cout << "Рекомендація: Пароль надто короткий. Мінімум 8 символів.\n";
            break;

        case 2:
            cout << "Рівень надійності: 2 - Слабкий\n";
            cout << "Рекомендація: Збільште довжину до 8+ символів і додайте цифри, великі літери або спеціальні символи.\n";
            break;

        case 3:
            cout << "Рівень надійності: 3 - Середній\n";
            cout << "Рекомендація: Додайте ще один тип символів або збільште довжину до 12.\n";
            break;

        case 4:
            cout << "Рівень надійності: 4 - Надійний\n";
            cout << "Рекомендація: Хороший пароль. Для максимуму 12+ символів і всі три типи символів.\n";
            break;

        case 5:
            cout << "Рівень надійності: 5 - Дуже надійний\n";
            cout << "Рекомендація: Відмінно. Змінювати нічого не потрібно.\n";
            break;

        default:
            cout << "Помилка визначення рівня надійності.\n";
            break;
    }

    // Без цифр і спеціальних символів пароль складається тільки з літер.
    if (hasDigits == "n" && hasSpecial == "n")
    {
        cout << "Попередження: пароль тільки з літер підбирається швидше.\n";
    }

    return 0;
}
