#include <iostream>
using namespace std;

int main() {
    int length;
    char d, u, s;

    cout << "Довжина пароля: ";
    if (!(cin >> length) || length < 1 || length > 64) {
        cout << "Помилка: довжина мусить бути від 1 до 64.\n";
        return 1;
    }

    cout << "Чи є цифри (y/n): "; 
    cin >> d;
    cout << "Чи є великі літери (y/n): "; 
    cin >> u;
    cout << "Чи є спеціальні символи (y/n): "; 
    cin >> s;

    if (!(d == 'y' || d == 'n') || !(u == 'y' || u == 'n') || !(s == 'y' || s == 'n')) {
        cout << "Помилка: введіть 'y' або 'n'.\n";
        return 1;
    }

    bool zifra = (d == 'y');
    bool caps = (u == 'y');
    bool special = (s == 'y');
    int types = zifra + caps + special; // true/false зчитується як 1/0

    if (length >= 8 && types >= 2) {
        cout << "Мінімальні вимоги пройдено.\n";
    } else {
        cout << "Мінімальні вимоги не пройдено.\n";
    }

    // Перше, що спрацює, визначає рівень
    int level;
    if (length < 6) {
        level = 1;
    } else if (length < 8 || types == 0) {
        level = 2;
    } else if (types == 1) {
        level = 3;
    } else if (length >= 12 && types == 3) {
        level = 5;
    } else {
        level = 4;
    }

    switch (level) {
        case 1:
            cout << "Рівень надійності: 1 - Дуже слабкий\n";
            cout << "Рекомендація: Пароль надто короткий. Мінімум 8 символів.\n";
            break;
        case 2:
            cout << "Рівень надійності: 2 - Слабкий\n";
            cout << "Рекомендація: Збільште довжину до 8+ символів і додайте цифри, великі літери або спеціальні символи.\n";
            break;
        case 3:
            cout << "Рівень надійності: 3 - Середній\n";
            cout << "Рекомендація: Додайте ще один тип символів або збільште довжину до 12.\n";
            break;
        case 4:
            cout << "Рівень надійності: 4 - Надійний    \n";
            cout << "Рекомендація: Хороший пароль. Для максимуму 12+ символів і всі три типи символів.\n";
            break;
        case 5:
            cout << "Рівень надійності: 5 - Дуже надійний\n";
            cout << "Рекомендація: Відмінно. Змінювати нічого не потрібно.\n";
            break;
        default:
            cout << "Помилка: невідомий рівень.\n";
            break;
    }

    if (!zifra && !special) {
        cout << "Попередження: пароль тільки з літер підбирається швидше.\n";
    }

    return 0;
}