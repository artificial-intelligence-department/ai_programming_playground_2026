#include <iostream>
#include <string>
#include <cmath>
using namespace std;

int main() {
    string model;
    double C, eff, P;
    int years, charge;

    // Зчитування вхідних даних
    cout << "Модель станції: ";             cin >> model;
    cout << "Паспортна ємність (Вт*год): "; cin >> C;
    cout << "Вік станції (років): ";        cin >> years;
    cout << "Рівень заряду (%): ";          cin >> charge;
    cout << "ККД інвертора (%): ";          cin >> eff;
    cout << "Потужність приладу (Вт): ";    cin >> P;

    // Якщо хоч одне зі значень не вдалося прочитати як число - завершуємо
    if (cin.fail()) { cout << "Помилка: введено не число.\n"; return 1; }

    // Перевірка допустимих меж кожного значення
    if (model.size() > 31)          { cout << "Помилка: назва моделі не довша за 31 символ.\n"; return 1; }
    if (C <= 0)                     { cout << "Помилка: ємність повинна бути більшою за 0.\n"; return 1; }
    if (years < 0 || years > 20)    { cout << "Помилка: вік станції мусить бути від 0 до 20.\n"; return 1; }
    if (charge < 0 || charge > 100) { cout << "Помилка: рівень заряду мусить бути від 0 до 100.\n"; return 1; }
    if (eff <= 0 || eff > 100)      { cout << "Помилка: ККД мусить бути більшим за 0 і не більшим за 100.\n"; return 1; }
    if (P <= 0)                     { cout << "Помилка: потужність повинна бути більшою за 0.\n"; return 1; }
    
    const double DEGRADATION_PER_YEAR = 2.0; // % втрати ємності акумулятора за рік

    // 1. Фактична ємність з урахуванням старіння акумулятора, Вт*год
    double C_eff = C * pow(1 - DEGRADATION_PER_YEAR / 100, years);
    // 2. Запас енергії при поточному рівні заряду, Вт*год
    double E_stored = C_eff * charge / 100;
    // 3. Корисна енергія, що дійде до приладу через інвертор, Вт*год
    double E_useful = E_stored * eff / 100;
    // 4. Втрати на перетворенні напруги в інверторі, Вт*год
    double E_loss = E_stored - E_useful;
    // 5. Час роботи приладу, годин
    double T = E_useful / P;
    int h = (int)T;                  // 6. Повні години
    int m = (int)((T - h) * 60);     // 7. Хвилини, що залишились

    // Вивід результату
    cout << "\n--- РЕЗУЛЬТАТИ РОЗРАХУНКУ ---\n";
    cout << "Модель:\t\t\t\t" << model << "\n";
    cout << "Паспортна ємність:\t\t" << C << " Вт*год\n";
    cout << "Вік станції:\t\t\t" << years << " р.\n";
    cout << "Фактична ємність:\t\t" << C_eff << " Вт*год\n";
    cout << "Рівень заряду:\t\t\t" << charge << " %\n";
    cout << "ККД інвертора:\t\t\t" << eff << " %\n";
    cout << "Запас енергії:\t\t\t" << E_stored << " Вт*год\n";
    cout << "Корисна енергія:\t\t" << E_useful << " Вт*год\n";
    cout << "Втрати на перетворенні:\t\t" << E_loss << " Вт*год\n";
    cout << "Час роботи:\t\t\t" << T << " год  = " << h << " год " << (m < 10 ? "0" : "") << m << " хв\n";
    return 0;
}