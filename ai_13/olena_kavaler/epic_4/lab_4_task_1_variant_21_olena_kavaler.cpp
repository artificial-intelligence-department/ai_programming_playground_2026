#include <iostream>
using namespace std;

int main() {

const int N = 100;
int n;

do {
    cout << "Введіть довжину " << endl;
    cin >> n;
    if (n <= 0 || n > N) cout << "Помилка: число не підходить" << endl;
} while (n <= 0 || n > N);

cout << "Введіть " << n << " елементів: " << endl;
int a[N];

for (int i = 0; i < n; i++) {
    cin >> a[i];
}

// K це номер елемента, з якого почнуться обидва друки
int K;
do {
    cout << "Введіть K (від " << 0 << " до " << n - 1 << "):" << endl;
    cin >> K;
    if (K < 0 || K >= n) {
        cout << "Помилка: число не підходить" << endl;
    }
} while (K < 0 || K >= n);

int i;

// вивід елементів вліво по кільцю 
i = K;
for (int j = 0; j < n; j++){
    cout << a[i] << " ";
    i = (i - 1 + n) % n; // перехід до попереднього елемента з замиканням кільця
}
cout << endl;

// додавання в кінець кільця першого та трьох останніх елементів
if (n + 4 <= N && n >= 3) {
    a[n] = a[0];
    a[n + 1] = a[n - 3];
    a[n + 2] = a[n - 2];
    a[n + 3] = a[n - 1];
    n = n + 4; // збільшуємо реальну довжину масиву на 4
} else {
    cout << "Додати елементи неможливо" << endl;
}

// друк оновленого масиву вправо по кільцю, починаючи з того ж K
i = K;
for (int j = 0; j < n; j++) {
    cout << a[i] << " ";
    i = (i + 1) % n;
}
cout << endl;

return 0;
}
