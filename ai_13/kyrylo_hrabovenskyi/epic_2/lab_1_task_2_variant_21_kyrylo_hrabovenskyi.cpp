#include <iostream>

using namespace std;

int main()
{
	// =========================================================================
	// СТРУКТУРНИЙ БЛОК 1: ВВЕДЕННЯ ВХІДНИХ ДАНИХ
	// (Ініціалізація та зчитування початкових значень змінних m та n з клавіатури)
	// =========================================================================
	cout << "enter m\n"; 
	double m; 
	cin >> m; 

	cout << "enter n\n"; 
	double n; 
	cin >> n; 

	// =========================================================================
	// СТРУКТУРНИЙ БЛОК 2: АРИФМЕТИЧНА ОПЕРАЦІЯ З ПОСТФІКСНИМ ІНКРЕМЕНТОМ
	// (Використання поточної n у виразі n - m з її наступним збільшенням на 1)
	// =========================================================================
	double result_1 = (n++) - m; 

	cout << "result of action is " << result_1 << endl; 
	cout << "after (n++) - m" << endl << "n = " << n << endl << "m = " << m << endl; 

	// =========================================================================
	// СТРУКТУРНИЙ БЛОК 3: ПЕРША ОПЕРАЦІЯ ПОРІВНЯННЯ З ПОСТФІКСНИМ ДЕКРЕМЕНТОМ
	// (Перевірка умови m > n для поточних значень та наступне зменшення m на 1)
	// =========================================================================
	bool result_2 = m-- > n; 

	if (result_2 == 1) 
	{
		cout << "result of action is true\n"; 
	}

	if (result_2 == 0) 
	{
		cout << "result of action is false\n"; 
	}

	cout << "after (m--) > n" << endl << "n = " << n << endl << "m = " << m << endl; 

	// =========================================================================
	// СТРУКТУРНИЙ БЛОК 4: ДРУГА ОПЕРАЦІЯ ПОРІВНЯННЯ З ПОСТФІКСНИМ ДЕКРЕМЕНТОМ
	// (Перевірка умови n > m для змінених значень та фінальне зменшення n на 1)
	// =========================================================================
	bool result_3 = n-- > m; 

	if (result_3 == 1) 
	{
		cout << "result of action is true\n"; 
	}

	if (result_3 == 0) 
	{
		cout << "result of action is false\n"; 
	}

	cout << "after (n--) > m" << endl << "n = " << n << endl << "m = " << m << endl; 
}
