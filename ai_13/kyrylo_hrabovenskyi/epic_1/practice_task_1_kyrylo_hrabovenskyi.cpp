// Підключення стандартних бібліотек для роботи з потоками введення-виведення та рядками
#include <iostream>
#include <string>
#include <clocale>
#include <iomanip>
#include <windows.h>

using namespace std;

int main() {
    // Налаштування кодування UTF-8 (65001) для коректного відображення українських літер у консолі Windows
    SetConsoleCP(65001);
    SetConsoleOutputCP(65001);

    // Налаштування виведення дробових чисел: фіксована точка та 2 знаки після коми
    cout << fixed << setprecision(2);

    // --- БЛОК ВВЕДЕННЯ ТА ВАЛІДАЦІЇ ДАНИХ ДЛЯ МОДЕЛІ СТАНЦІЇ ---
    cout << "вкажіть модель зарядної станції\n";
    string model;
    cin >> model; // Зчитування назви моделі (до першого пробілу)

    // Перевірка довжини назви моделі (обмеження до 31 символу)
    if (model.length() > 31) {
        cout << "\n ВИВІД ПРОГРАМИ \n";
        cout << "Задовга назва Має бути не більш як 31 символ\n";
        cout << "Модель " << model << "\n";
        return 1; // Завершення програми з кодом помилки
    }

    // --- БЛОК ВВЕДЕННЯ ТА ВАЛІДАЦІЇ ДАНИХ ДЛЯ ПАСПОРТНОЇ ЄМНОСТІ ---
    cout << "вкажіть паспортну ємність Вт год\n";
    float C; // Змінна для збереження паспортної ємності
    cin >> C;
    
    // Перевірка: ємність не може бути нульовою або від'ємною
    if (C <= 0) { 
        cout << "\n ВИВІД ПРОГРАМИ \n";
        cout << "Модель " << model << "\n";
        cout << "Паспортна ємність " << C << " Вт god\n";
        cout << "Помилка число не може бути менше нуля\n";
        return 1; 
    }

    // --- БЛОК ВВЕДЕННЯ ТА ВАЛІДАЦІЇ ДАНИХ ДЛЯ ВІКУ СТАНЦІЇ ---
    cout << "вкажіть вік станції\n";
    int years;
    cin >> years;
    
    // Перевірка верхньої межі віку (максимум 20 років)
    if (years > 20) {
        cout << "\n ВИВІД ПРОГРАМИ \n";
        cout << "Модель " << model << "\n";
        cout << "Паспортна ємність " << C << " Вт год\n";
        cout << "Вік станції " << years << " років\n";
        cout << "Помилка вік має бути в межах від 0 до 20 років\n";
        return 1;
    }
    // Перевірка нижньої межі віку (мінімум 0 років)
    if (years < 0) {
        cout << "\n ВИВІД ПРОГРАМИ \n";
        cout << "Модель " << model << "\n";
        cout << "Паспортна ємність " << C << " Вт год\n";
        cout << "Вік станції " << years << " років\n";
        cout << "Помилка вік має бути в межах від 0 до 20 років\n";
        return 1;
    }

    // --- БЛОК ВВЕДЕННЯ ТА ВАЛІДАЦІЇ ДАНИХ ДЛЯ РІВНЯ ЗАРЯДУ ---
    cout << "вкажіть рівень заряду\n";
    int charge;
    cin >> charge;
    
    // Перевірка верхньої межі заряду акумулятора (максимум 100%)
    if (charge > 100) {
        cout << "\n ВИВІД ПРОГРАМИ \n";
        cout << "Модель " << model << "\n";
        cout << "Паспортна ємність " << C << " Вт год\n";
        cout << "Вік станції " << years << " років\n";
        cout << "Помилка рівень заряду має бути від 0 до 100\n";
        return 1;
    }
    // Перевірка нижньої межі заряду акумулятора (мінімум 0%)
    if (charge < 0) {
        cout << "\n ВИВІД ПРОГРАМИ \n";
        cout << "Модель " << model << "\n";
        cout << "Паспортна ємність " << C << " Вт год\n";
        cout << "Вік станції " << years << " років\n";
        cout << "Помилка рівень заряду має бути від 0 до 100\n";
        return 1;
    }

    // --- БЛОК ВВЕДЕННЯ ТА ВАЛІДАЦІЇ ДАНИХ ДЛЯ ККД ІНВЕРТОРА ---
    cout << "напишіть ККД інвестора\n";
    double eff; // Змінна для коефіцієнта корисної дії інвертора
    cin >> eff;
    
    // Перевірка верхньої межі ККД (максимум 100%)
    if (eff > 100) {
        cout << "\n ВИВІД ПРОГРАМИ \n";
        cout << "Модель " << model << "\n";
        cout << "Паспортна ємність " << C << " Вт god\n";
        cout << "Рівень заряду " << charge << "\n";
        cout << "Помилка ККД має бути від 0 до 100\n";
        return 1;
    }
    // Перевірка нижньої межі ККД (мінімум 0%)
    if (eff < 0) {
        cout << "\n ВИВІД ПРОГРАМИ \n";
        cout << "Модель " << model << "\n";
        cout << "Паспортна ємність " << C << " Вт god\n";
        cout << "Рівень заряду " << charge << "\n";
        cout << "Помилка ККД має бути від 0 до 100\n";
        return 1;
    }

    // --- БЛОК ВВЕДЕННЯ ТА ВАЛІДАЦІЇ ДАНИХ ДЛЯ ПОТУЖНОСТІ СПОЖИВАЧА ---
    cout << "напишіть потужність\n";
    double p; // Потужність підключеного пристрою
    cin >> p;
    
    // Перевірка на від'ємну або нульову потужність навантаження
    if (p <= 0) {
        cout << "ВИВІД ПРОГРАМИ \n";
        cout << "Модель \n" << model << "\n";
        cout << "Паспортна ємність \n" << C << " Вт год\n";
        cout << "Вік станції \n" << years << " років рік роки\n";
        cout << "Рівень заряду становить \n" << charge << "\n";
        cout << "ККД інвестора становить \n" << eff << "\n";
        cout << "потужність менша 0 Нічого собі\n";
        cout << "потужність становить \n" << p << " Вт\n";
        return 1;
    }

    // --- БЛОК МАТЕМАТИЧНИХ РОЗРАХУНКІВ ---
    
    // Обчислення залишкового коефіцієнта ємності. 
    // Щороку станція втрачає 2% ємності (ділення 2.0 / 100.0 дає відсоток деградації)
    double C_eff1 = 1.0 - (2.0 / 100.0 * years); 
    
    // Фактична ємність акумулятора з урахуванням його старіння/віку
    double C_eff = C * C_eff1; 
    
    // Запас енергії, що фізично є в батареї на основі поточного відсотка заряду
    double E_stored = C_eff * charge / 100.0; 
    
    // Корисна енергія, яку ми реально отримаємо на виході після втрат в інверторі (перетворення DC -> AC)
    double E_useful = E_stored * eff / 100.0; 
    
    // Обчислення енергії, яка перетворилася на тепло через ККД (втрати)
    double E_loss = E_stored - E_useful; 
    
    // Загальний розрахунковий час роботи пристрою у годинах (дробове число)
    double T = E_useful / p; 
    
    // Виділення цілої частини годин шляхом відсікання дробів
    int h = T; 
    
    // Обчислення залишку хвилин: дробову частину години множимо на 60 хвилин
    int m = (T - h) * 60; 

    // --- БЛОК ФОРМУВАННЯ ТА ВИВЕДЕННЯ ЗВІТУ ---
    cout << "\n ВИВІД ПРОГРАМИ \n";
    // Використання маніпулятора setw(15) для вирівнювання значень по центру/всередині поля виводу
    cout << "Модель" << setw(15) << internal << model << "\n";
    cout << "Паспортна ємність Вт год" << setw(15) << internal << C << "\n";
    cout << "Вік станції років" << setw(15) << internal << years << "\n";
    cout << "Фактична ємність Вт god" << setw(15) << internal << C_eff << "\n";
    cout << "Рівень заряду" << setw(15) << internal << charge << "\n";
    cout << "ККД інвертора" << setw(15) << internal << eff << "\n";
    cout << "Запас енергії Вт год" << setw(15) << internal << E_stored << "\n";
    cout << "Корисна енергія Вт год" << setw(15) << internal << E_useful << "\n";
    cout << "Витрати на перетворення Вт год" << setw(15) << internal << E_loss << "\n";
    
    // Фінальний результат роботи станції у форматі ХХ год ХХ хв
    cout << "Час роботи пристрою" << setw(6) << internal << h << " год" << setw(2) << m << " хв\n";
    cout << "\n";

    return 0; // Успішне завершення програми
}