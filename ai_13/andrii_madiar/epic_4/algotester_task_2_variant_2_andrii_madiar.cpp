#include <iostream>
using namespace std;
int main(){
    int N = 0;
    cin >> N;
    int Nnew = N;//змінна щоб випадково не вийти за межі масиву
    int* arr = new int[N];//динамічний масив з розміром N
    int a, b, c;
    for(int i=0; i<N; i++){//ввід елементів масиву
        cin >> arr[i];
    }
    cin >> a >> b >> c;//ввід чисел які хочем вилусити
    for(int i=0; i<Nnew; i++){
    if(arr[i] == a || arr[i] == b || arr[i] == c){//вилучення елементів
        for(int j=i; j<Nnew-1; j++){
            arr[j] = arr[j+1];//імітуєм видалення елементу через зсув всіх елементів справа від вилучених на одну позицію вліво
        }
        Nnew--;
        i--;//не переходим на наступний крок бо зсунувши нам знову треба перевірити і-вий елемент
    }
    }
    if(Nnew<=1){//перевірки у випадках якщо елементів не залишилося або він лише один
        cout << 0;
        return 0;
    }
    cout << Nnew-1 << "\n";//вивід розміру нового масиву і нових елементів
    for(int i=0; i<Nnew-1; i++){
        cout << arr[i]+arr[i+1] << " ";
    }
    delete[] arr;//очищую динамічний масив
    return 0;
}