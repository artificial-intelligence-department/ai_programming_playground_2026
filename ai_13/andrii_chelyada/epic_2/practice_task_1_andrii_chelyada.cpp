#include <iostream>
using namespace std;

int main() {
    // length: довжина пароля
    // securityLevel: підсумковий рівень надійності (від 1 до 5)
    // typesOfCharacters: лічильник типів символів у паролі (цифри, спецсимволи,)
    int length, securityLevel, typesOfCharacters;
    typesOfCharacters = 0;   // лічильник обов'язково починаємо з нуля, бо далі до нього додаємо

    // Введення довжини пароля
    cout << "Введіть довжину пароля: ";
    cin >> length;

    // Перевірка довжини: допустимо від 1 до 64 символів, інакше завершуємо програму з помилкою
    if (length < 1 || length > 64) {
        cout << "Неприпустима довжина пароля" << endl;
        return 1;
    }

    // Відповіді користувача на питання «є / немає»: 'y' (так) або 'n' (ні)
    char numbers, uppercaseLetters, specialCharacters;

    // --- Цифри ---
    cout << "Чи є числа у паролі?(y/n): ";
    cin >> numbers;

    // Перевірка вводу: приймаємо лише 'y' або 'n', усе інше є помилкою
    if (numbers != 'y' && numbers != 'n') {
        cout << "Відповідь повинна бути 'y' або 'n'" << endl;
        return 1;
    }

    // Якщо цифри є, рахуємо ще один тип символів
    if (numbers == 'y') {
        typesOfCharacters += 1;
    }

    // --- Спеціальні символи ---
    cout << "Чи є спеціальні символи у паролі?(y/n): ";
    cin >> specialCharacters;

    // Перевірка вводу
    if (specialCharacters != 'y' && specialCharacters != 'n') {
        cout << "Відповідь повинна бути 'y' або 'n'" << endl;
        return 1;
    }

    // Якщо спецсимволи є, рахуємо ще один тип
    if (specialCharacters == 'y') {
        typesOfCharacters += 1;
    }

    // --- Великі літери ---
    cout << "Чи є великі літери у паролі?(y/n): ";
    cin >> uppercaseLetters;

    // Перевірка вводу
    if (uppercaseLetters != 'y' && uppercaseLetters != 'n') {
        cout << "Відповідь повинна бути 'y' або 'n'" << endl;
        return 1;
    }

    // Якщо великі літери є, рахуємо ще один тип
    if (uppercaseLetters == 'y') {
        typesOfCharacters += 1;
    }

    // Рівень надійності: правила перевіряються зверху вниз,
    // перше, що спрацювало, визначає рівень (решта пропускаються завдяки else if)
    if (length < 6) {
        // 1 - дуже слабкий: пароль надто короткий
        securityLevel = 1;
    }
    else if (length < 8 || typesOfCharacters == 0) {
        // 2 - слабкий: коротший за 8 АБО немає жодного додаткового типу символів
        securityLevel = 2;
    }
    else if (typesOfCharacters == 1) {
        // 3 - середній: рівно один додатковий тип символів
        securityLevel = 3;
    }
    else if (length >= 12 && typesOfCharacters == 3) {
        // 5 - дуже надійний: довжина від 12 І всі три типи символів
        securityLevel = 5;
    }
    else {
        // 4 - надійний: усі інші випадки
        securityLevel = 4;
    }

    // Мінімальні вимоги: довжина від 8 І щонайменше 2 типи символів.
    // bool зберігає лише два значення: true (виконано) або false (не виконано)
    bool minimumSecurityLevel;
    if (length < 8 || typesOfCharacters < 2) {
        minimumSecurityLevel = false;
    }
    else {
        minimumSecurityLevel = true;
    }

    cout << endl;   // порожній рядок для відступу між введенням і результатами

    // Виведення результату перевірки мінімальних вимог
    if (!minimumSecurityLevel) {
        cout << "Пароль не відповідає мінімальному рівню безпеки" << endl;
    }
    else {
        cout << "Пароль відповідає мінімальному рівню безпеки" << endl;
    }

    // Вивід рівня та рекомендації: switch порівнює securityLevel зі значеннями case
    switch (securityLevel) {
        case 1:
            cout << "Рівень безпеки пароля: Дуже низький" << endl
                 << "Рекомендація: пароль має містити хоча б 8 символів" << endl;
            break;   // break потрібен, щоб не «провалитися» у наступний case
        case 2:
            cout << "Рівень безпеки пароля: Низький" << endl
                 << "Рекомендація: пароль має містити хоча б 8 символів, а також велику літеру, або спеціальний символ, або цифру" << endl;
            break;
        case 3:
            cout << "Рівень безпеки пароля: Середній" << endl
                 << "Рекомендація: щоб покращити пароль, додайте ще один тип символів або збільшіть довжину до 12 символів" << endl;
            break;
        case 4:
            cout << "Рівень безпеки пароля: Високий" << endl
                 << "Рекомендація: щоб покращити рівень безпеки, збільшіть довжину до 12+ символів та додайте різні типи символів" << endl;
            break;
        case 5:
            cout << "Рівень безпеки пароля: Дуже високий" << endl
                 << "Рекомендацій немає, пароль відповідає найвищому рівню безпеки" << endl;
            break;
        default:
            // сюди потрапимо лише якщо securityLevel має неочікуване значення
            cout << "Неможливо визначити рівень безпеки" << endl;
            break;
    }

    // Попередження: жодного з трьох типів немає, отже пароль складається лише з малих літер
    if (specialCharacters == 'n' && uppercaseLetters == 'n' && numbers == 'n') {
        cout << "Пароль, який складається лише з малих літер, вгадати легше" << endl;
    }

    return 0;   // програма завершилась успішно
}