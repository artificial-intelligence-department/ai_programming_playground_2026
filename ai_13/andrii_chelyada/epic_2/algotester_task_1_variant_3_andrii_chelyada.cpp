/* Алготестер, завдання 1, варіант 3, Челяда Андрій, ШІ-13 

Персонажу по одному дають сторони 5 кубів 𝑎1.⁢.5, з яких він будує піраміду.

Коли він отримує куб з ребром 𝑎𝑖 - він його ставить на існуючий, перший ставить на підлогу (вона безмежна).

Якщо в якийсь момент об’єм куба у руці (який будуть ставити) буде більший ніж у куба на вершині піраміди - персонаж програє і гра закінчується. Розмір усіх наступних кубів після програшу не враховується.

Тобто якщо 𝑎𝑖−1 <𝑎𝑖 - це програш.

Ваше завдання - сказати як закінчиться гра.

Input
5 цілих чисел 𝑎1..𝑎5 - сторони кубів

Output
Існуючі варіанти:

LOSS - якщо персонаж не зможе поставити куб.

WIN - якщо персонаж зможе поставити усі куби

ERROR - якщо сторона куба буде мати неможливу довжину, тобто 𝑎𝑖 <= 0

*/

#include <iostream>
using namespace std;

int main() {
    // сторони п'яти кубів; long long, бо в тестах є числа порядку 10^12
    long long side1, side2, side3, side4, side5;
    cin >> side1 >> side2 >> side3 >> side4 >> side5;

    // Перевірки йдуть по черзі, куб за кубом, у порядку, в якому їх дають персонажу.
    // Одразу після першого ERROR або LOSS програма завершується,
    // бо розмір кубів після програшу не враховується.

    // Куб 1: ставиться на підлогу, порівнювати його ні з чим не треба,
    // перевіряємо лише, чи можлива довжина ребра
    if (side1 <= 0) {
        cout << "ERROR" << endl;
        return 0;
    }

    // Куб 2: спочатку перевіряємо, чи ребро можливе
    if (side2 <= 0) {
        cout << "ERROR" << endl;
        return 0;
    }

    // потім порівнюємо з кубом на вершині (side1): більший куб поставити не можна
    if (side2 > side1) {
        cout << "LOSS" << endl;
        return 0;
    }

    // Куб 3: на вершині тепер side2
    if (side3 <= 0) {
        cout << "ERROR" << endl;
        return 0;
    }

    if (side3 > side2) {
        cout << "LOSS" << endl;
        return 0;
    }

    // Куб 4: на вершині тепер side3
    if (side4 <= 0) {
        cout << "ERROR" << endl;
        return 0;
    }

    if (side4 > side3) {
        cout << "LOSS" << endl;
        return 0;
    }

    // Куб 5: на вершині тепер side4
    if (side5 <= 0) {
        cout << "ERROR" << endl;
        return 0;
    }

    if (side5 > side4) {
        cout << "LOSS" << endl;
        return 0;
    }

    // Жодна перевірка не спрацювала: усі п'ять кубів успішно поставлено
    cout << "WIN" << endl;
    return 0;
}