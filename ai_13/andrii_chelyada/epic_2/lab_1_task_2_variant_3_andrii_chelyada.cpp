#include <iostream>
#include <iomanip>
using namespace std;

int main() {
    int n, m;

    cout << "Введіть n: ";
    cin >> n;
    cout << "Введіть m: ";
    cin >> m;
    cout << "\n";

    // Перший вираз n---m
    // компілятор читає його як (n--) - m
    // спочатку береться поточне значення n, від нього віднімається m, і лише після цього n зменшується на 1
    int result1 = n --- m;
    cout << "Результат першого виразу (n --- m): " << result1 << endl;

    // Другий вираз m--<n
    // компілятор читає його як (m--) < n
    // спочатку старе значення m порівнюється з n (n вже зменшене в першому виразі), після чого m зменшується на 1
    bool result2 = m-- < n;
    cout << "Результат другого виразу (m--<n): " << result2 << endl;

    // Третій вираз n++>m
    // компілятор читає його як (n++) > m
    // спочатку старе значення n порівнюється з m (m вже зменшене в другому виразі), після чого n збільшується на 1
    bool result3 = n++ > m;
    cout << "Результат третього виразу (n++>m): " << result3 << endl;

    return 0;
}