/*
У Зеника сьогодні дуже складний екзамен з лінійної алгебри та аналітичної геометрії.
Щасливим вважається квиток, у номері якого є послідовність цифр 47.
Якщо квиток щасливий — виводимо YES, інакше — NO.
*/

#include <iostream>
using namespace std;

int main() {
    // Зберігаємо номер квитка як рядок символів.
    // Масив на 12 символів дозволяє зберегти до 11 цифр і символ завершення '\0'.
    char n[12];

    // Зчитуємо номер квитка.
    cin >> n;

    // Перебираємо символи номера від першого до останнього.
    // Цикл завершується, коли зустрічаємо '\0' — кінець рядка.
    for (int i = 0; n[i] != '\0'; i++) {

        // Перевіряємо, чи поточний символ — '4',
        // а наступний символ — '7'.
        if (n[i] == '4' && n[i + 1] == '7') {
            cout << "YES" << endl;
            return 0;
        }
    }

    // Якщо послідовність 47 не знайдена, квиток нещасливий.
    cout << "NO" << endl;

    return 0;
}