#include <iostream>
#include <iomanip>
using namespace std;

int main() {

// Змінні для довжини пароля та кількості типів символів
int lenth = 0;
int num_oftypes = 0;
char answer1, answer2, answer3;

// Введення довжини пароля
cout << "Введіть довжину пароля: ";
cin >> lenth;
if (lenth < 1 || lenth > 64) {
    cout << "Помилка: довжина пароля повинна бути в межах від 1 до 64 символів." << endl;
    return 1;
}

// Перевірка наявності цифр
cout << "Чи є цифри? (y/n): ";
cin >> answer1;
if (answer1 != 'y' && answer1 != 'n') {
    cout << "Помилка: введіть 'y' або 'n'." << endl; 
    return 1;   
}

if (answer1 == 'y') {
    num_oftypes++;
}

// Перевірка наявності великих літер
cout << "Чи є великі літери? (y/n): ";
cin >> answer2;
if (answer2 != 'y' && answer2 != 'n') {
    cout << "Помилка: введіть 'y' або 'n'." << endl;
    return 1;
}  

if (answer2 == 'y') {
    num_oftypes++;
}

// Перевірка наявності спеціальних символів
cout << "Чи є спеціальні символи? (y/n): ";
cin >> answer3;
if (answer3 != 'y' && answer3 != 'n') {
    cout << "Помилка: введіть 'y' або 'n'." << endl;
    return 1;
}

if (answer3 == 'y') {
    num_oftypes++;
}

cout << endl;

// Перевірка мінімальних вимог до пароля
if (lenth > 7 && num_oftypes > 1) {
    cout << "Мінімальні вимоги: ПРОЙДЕНО" << endl;
}
else {
    cout << "Мінімальні вимоги: НЕ ПРОЙДЕНО" << endl;
    
}

// Попередження про пароль, який складається лише з літер
if (num_oftypes == 1) {
    cout << "Попередження: пароль тільки з літер підбирається швидше." << endl;
}

// Визначення рівня надійності пароля
int level = 0;
if (lenth < 6) {
    level = 1;
} else if (lenth < 8 || num_oftypes == 0) {
    level = 2;
} else if (num_oftypes == 1) {
    level = 3;
} else if (lenth > 11 && num_oftypes == 3) {
    level = 4;
} else {
    level = 5;
}

// Виведення рекомендацій залежно від рівня надійності
switch (level) {
    case 1:
        cout << "Рівень надійності: 1 - Дуже слабкий" << endl;
        cout << "Рекомендація: Пароль надто короткий. Мінімум 8 символів." << endl;
        break;
    case 2:
        cout << "Рівень надійності: 2 - Слабкий" << endl;
        cout << "Рекомендація: Збільште довжину до 8+ символів і додайте цифри, великі літери або спеціальні символи." << endl;
        break;
    case 3:
        cout << "Рівень надійності: 3 - Середній" << endl;
        cout<< "Рекомендація: Дoдайте ще один тип символів або збільште довжину до 12." << endl;
        break;
    case 4:
        cout << "Рівень надійності: 4 - Надійний" << endl;
        cout<< "Рекомендація: Хороший пароль. Для максимуму 12+ символів і всі три типи символів." << endl;
        break;
    case 5:
        cout << "Рівень надійності: 5 - Дуже надійний" << endl;
        cout<< "Рекомендація: Відмінно. Змінювати нічого не потрібно." << endl;
        break;

    // Виведення повідомлення про невідомий рівень надійності    
    default:
        cout << "Помилка: невідомий рівень надійності." << endl;
        break;    
}
return 0;
}
    