#include <iostream>
using namespace std;

int main() {
    // Масив з 5 чисел, які перевіряються на умову перемоги.
    long long a[5];

    // Зчитуємо 5 значень з клавіатури.
    for (int i = 0; i < 5; i++) cin >> a[i];

    // Перевіряємо кожне число: число має бути додатним.
    for (int i = 0; i < 5; i++) {
        if (a[i] <= 0) {
            // Якщо хоча б одне число <= 0, результат — ERROR.
            cout << "ERROR" << endl;
            return 0;
        }
        if (i > 0 && a[i - 1] < a[i]) {
            // Якщо попереднє число менше поточного, послідовність зростає — LOSS.
            cout << "LOSS" << endl;
            return 0;
        }
    }

    // Якщо всі перевірки пройдені, то це виграшна послідовність.
    cout << "WIN" << endl;
    return 0;
}