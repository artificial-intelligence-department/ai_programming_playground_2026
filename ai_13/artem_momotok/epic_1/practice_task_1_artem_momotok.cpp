#include <iostream>
#include <iomanip>
#include <cmath>
using namespace std;
int main()
{
  // Оголошення змінних для параметрів зарядної станції
  string model;
  double C, eff, P, C_eff, E_stored, E_useful, E_loss, T;
  int years, charge,h,m;
  const double battery_degradation = 2.0; // Щорічне зменшення ємності, %

  // Введення базових даних про станцію
  cout << "Введіть модель зарядної станції:" ;
  cin >> model;

  // Перевірка довжини назви моделі
  if (model.length() > 31) 
  {
    cout << "Помилка: назва моделі задовга" << endl;
    return 1;
  }
  
  // Введення паспортної ємності акумулятора
 cout << "Введіть паспортну ємність:" ;
  cin >> C;

  // Перевірка коректності ємності
  if (C <= 0) 
  {
    cout << "Помилка: неправильна паспортна ємність" << endl;
    return 1;
  }

  // Введення віку пристрою
cout << "Введіть вік зарядної станції:" ;
  cin >> years;

  // Перевірка допустимого віку
  if (years < 0 || years > 20) 
  {
    cout << "Помилка: неправильний вік зарядної станції" << endl;
    return 1;
  }
 
  // Введення поточного рівня заряду
cout << "Введіть рівень заряду(%):" ;
  cin >> charge;

  // Перевірка рівня заряду в межах 0..100%
  if (charge < 0 || charge > 100) 
  {
    cout << "Помилка: неправильний рівень заряду" << endl;
    return 1;
  }  

  // Введення ККД інвертора
cout << "Введіть ККД інвертора(%):" ;
  cin >> eff;

  // Перевірка коректності ККД
  if (eff <= 0 || eff > 100) 
  {
    cout << "Помилка: неправильний ККД інвертора" << endl;
    return 1;
  }  

  // Введення потужності пристрою
cout << "Введіть потужність зарядної станції:" ;
  cin >> P;

  // Перевірка потужності
  if (P <= 0) 
  {
    cout << "Помилка: неправильна потужність зарядної станції" << endl;
    return 1;
  }  

  // Розрахунок фактичної ємності з урахуванням старіння
C_eff = C * pow(1 - battery_degradation / 100, years) ;

  // Розрахунок накопиченої енергії з урахуванням заряду
E_stored = C_eff * charge / 100;

  // Корисна енергія після перетворення інвертором
E_useful = E_stored * eff / 100;

  // Втрати при перетворенні енергії
E_loss = E_stored - E_useful;

  // Час роботи при заданій потужності навантаження
T = E_useful / P;

  // Виділення цілої кількості годин та хвилин
h =  int(T);

m = int(((T - h) * 60));

cout << endl; 

  // Виведення зведених результатів розрахунків
cout << left << setw(60) << "Модель зарядної станції:                    " << model << endl;

cout << left << setw(60) << "Паспортна ємність:                          " << C << " А·год" << endl;

cout << left << setw(60) << "Вік зарядної станції:                       " << years << " років" << endl;

cout << left << setw(60) << "Фактична ємність:                           " << C_eff << " А·год" << endl;

cout << left << setw(60) << "Рівень заряду:                              " << charge << "%" << endl;

cout << left << setw(60) << "ККД інвертора:                              " << eff << "%" << endl;

cout << left << setw(60) << "Запас енергії:                              "  << E_stored << " Вт·год" << endl;

cout << left << setw(60) << "Корисна енергія:                            "  << E_useful << " Вт·год" << endl;

cout << left << setw(60) << "Втрати на перетворенні:                     "  << E_loss << " Вт·год" << endl;

cout << left << setw(60) << "Час роботи: " << h << " годин " << m << " хвилин" << endl;   

return 0;
} 