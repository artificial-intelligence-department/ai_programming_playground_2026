#include <iostream>

int main() {
    // Зчитуємо кількість зубів і порогове значення заточеності.
    int n;
    long long k;
    std::cin >> n >> k;

    // cur — довжина поточної послідовності, best — найбільша знайдена довжина.
    int cur = 0, best = 0;
    for (int i = 0; i < n; i++) {
        // Зчитуємо чергове число.
        long long a;
        std::cin >> a;
        // Якщо число не менше за поріг, продовжуємо послідовність.
        if (a >= k) {
            cur++;
            // Зберігаємо новий максимум довжини послідовності.
            if (cur > best) best = cur;
        } else {
            // Менше за поріг число перериває послідовність.
            cur = 0;
        }
    }

    // Виводимо довжину найдовшої послідовності.
    std::cout << best << std::endl;
    return 0;
}