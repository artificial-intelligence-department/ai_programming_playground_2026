#include <iostream>

int main() {
    // Змінна для збереження накопиченої суми.
    int sum = 0;

    // Перебираємо числа, кратні 3, від 3 до 200 включно.
    for (int i = 3; i <= 200; i += 3) {
        // Додаємо поточне число до суми.
        sum += i;
    }
    // Виводимо результат обчислення.
    std::cout << "Сума чисел, кратних 3, від 3 до 200: " << sum << std::endl;
    return 0;
}