#include <iostream>
#include <string>

int main() {
    // Зчитуємо вхідний рядок.
    std::string n;
    std::cin >> n;

    // Масив позначок для 26 великих латинських літер і лічильник унікальних літер.
    bool used[26] = {false};
    int count = 0;

    // Перебираємо всі символи рядка.
    for (int i = 0; i < n.length(); i++) {
        // Перетворюємо літеру на індекс від 0 до 25.
        int x = n[i] - 'A';

        // Якщо літера ще не зустрічалася, позначаємо її та збільшуємо лічильник.
        if (!used[x]) {
            used[x] = true;
            count++;
        }
    }

    // Виводимо кількість різних літер у рядку.
    std::cout << count << std::endl;

    return 0;
}