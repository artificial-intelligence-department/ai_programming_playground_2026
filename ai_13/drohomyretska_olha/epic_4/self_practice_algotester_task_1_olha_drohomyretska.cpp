/*
Задача: Замовлення від стоматологів
Дрогомирецька Ольга 
ШІ-13

Умова:
До компанії Зеника й Марічки PLVIV звернулася із замовленням стоматологія.
Як відомо, верхня та нижня щелепи здорової людини містять по 𝑛 зубів.
Щелепа пацієнта стоматології задається рядком з 𝑛 символів 0 і 1, де 0 позначає, що на відповідній позиції нема зуба, а 1 — є зуб.
Стоматологи вважають, що пацієнт може жувати, якщо в нього існують такі два зуби, що один є безпосередньо над іншим.
Напишіть для стоматології програму, яка визначає, чи пацієнт може жувати.
Вхідні дані
У першому рядку задано ціле число 𝑛 — кількість зубів на щелепі здорової людини.
У другому рядку записано 𝑛 символів 0 і 1 — опис верхньої щелепи.
У третьому рядку в тому самому форматі задано опис нижньої щелепи.
Вихідні дані
В одному рядку виведіть Yes, якщо пацієнт може жувати, або No, якщо не може.
Обмеження
1 ≤ 𝑛 ≤ 1000.
*/

#include <iostream> 
using namespace std;

int main () {
    int n;
    cin >> n;

    char upper[1000];
    char lower[1000];
    cin >> upper >> lower;

    //шукаю пару зубів на однаковій позиції
    for (int i = 0; i < n; i++) {
        if (upper[i] == '1' && lower[i] == '1') {
            cout << "Yes" << endl;
            return 0;
        }
    }
    //якшо пари немає, пацієнт не може жувати
    cout << "No" << endl;
    return 0;
}