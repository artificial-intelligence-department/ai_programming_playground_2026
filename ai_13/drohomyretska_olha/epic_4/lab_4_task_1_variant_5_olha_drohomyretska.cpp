#include <iostream>
#include <cstdlib> 
#include <ctime>

using namespace std;

int main () {
    srand(time(0)); //iніціалізація генератора випадкових чисел
    
    int mas[200];
    int n;

    cout << "Введіть кількість елементів масиву (1-100): ";

    if (!(cin >> n) || n < 1 || n > 100) {
        cout << "Помилка. Кількість елементів має бути від 1 до 100." << endl;
        return 1;
    }
    //рандомайзер дає значення від 0 до 99
    for (int i = 0; i < n; i++) {
        *(mas + i) = rand() % 100;
    }

    //друкую початковий масив
    for (int i = 0; i < n; i++) {
        cout << *(mas + i) << " ";
    }
    cout << endl;

    //видаляю елементи кратні 7
    for (int i = 0; i < n; i++) {
        if (*(mas + i) % 7 == 0) {
            for (int j = i; j < n - 1; j++) {
                *(mas + j) = *(mas + j + 1);
            }
            n--; //зменшую розмір масиву
            i--; //повертаюся на попередній індекс, щоб перевірити новий елемент
        }
    }
    //друкую масив після видалення
    for (int i = 0; i < n; i++) {
        cout << *(mas + i) << " ";
    }
    cout << endl;

    //після кожного непарного числа вставляю 0
    for (int i = 0; i < n; i++) {
        if (*(mas + i) % 2 != 0) {
            for (int j = n; j > i + 1; j--) {
                *(mas + j) = *(mas + j - 1); //зсуваю наступні елементи вправо, починаючи з кінця
            }
            *(mas + i + 1) = 0; 
            n++;
            i++; //пропускаю перевірку вставленого 0
        }
    }

    cout << "Масив після перетворень: ";
    for (int i = 0; i < n; i++) {
        cout << *(mas + i) << " ";
    }
    cout << endl;
    return 0;
}