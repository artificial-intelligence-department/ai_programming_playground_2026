/*
Задача: Різноманітні букети
Дрогомирецька Ольга
ШІ - 13

Умова:
Зеник нещодавно посварився з Марічкою, адже не дарував їй жодних квітів протягом останніх сорока семи днів. Він вирішив спробувати виправити цю ситуцію, тож пішов у сад і нарвав 𝑟 червоних і 𝑏 синіх тюльпанів. Зеник знає, що Марічка любить букети, що складаються рівно з 𝑛 квітів, і їй подобаються лише ті, яких вона ніколи раніше не бачила.
Зеник вирішив скласти з цього набору тюльпанів різні букети, щоб дарувати їх щодня Марічці.
Два букети вважаються різними, якщо вони містять різну кількість червоних або різну кількість синіх квітів.
Чи можете порахувати максимальну кількість букетів, що може скласти Зеник?
Вхідні дані
У єдиному рядку задано три цілих числа 𝑟, 𝑏, 𝑛 — кількість червоних, синіх тюльпанів відповідно та розмір букету, що подобається Марічці.
Вихідні дані
Виведіть одне ціле число — максимальну кількість різних букетів, що може скласти Зеник.
Обмеження
1 ≤𝑟,𝑏,𝑛 ≤109.
*/

#include <iostream>
using namespace std;

int main() {
    long long r, b, n;
    cin >> r >> b >> n;

    long long left = 0;

    //букетів не може бути більше, ніж кількість червоних або синіх тюльпанів
    long long right = (r + b) / n;
    //існує лише n + 1 різних складів букета
    if (right > n + 1) {
        right = n + 1;
    }
    while (left < right) {
        //беру середину, округлюючи вгору, бо якщо mid не підходить, то і менші значення теж не підходять
        long long  k = left + (right - left + 1) / 2;
        
        //мінімальна потрібна кількість квітів кожного кольору
        long long need = k * (k - 1) / 2;

        if (need <= r && need <= b && k * n <= r + b) {
            //к букетів скласти можна - пробую більше
            left = k;
        } else {
            right = k - 1; //не можемо скласти k букетів
        }
    }
    cout << left << endl;
    return 0;
}