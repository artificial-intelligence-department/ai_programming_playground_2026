#include <iostream>
#include <string>
#include <cmath>
#include <iomanip>


using namespace std;

int main(){

    // Ввід та перевірка моделі станції 
    string ModelStation;
    cout << "Введіть назву моделі станції:     ";
    cin >> ModelStation;

    // Назва не повинна перевищувати 31 символ і не повинна містити пробілів
    if (ModelStation.length()>31 || ModelStation.find(' ')!= string::npos ){
        cout << "Неправильна назва моделі станції" << endl;
        return 1;
    }

    //  Ввід та перевірка паспортної ємності станції 
    double capacity;
    cout << "Введіть ємність станції у Вт*год:   ";
    cin >> capacity;

    // Ємність не може бути від'ємною
    if (capacity < 0 ){
        cout << "Ємність станції не може бути меншою за 0" << endl;
        return 1;
    }

    // Ввід та перевірка віку станції 
    int age; 
    cout << "Введіть вік станції у роках:    ";
    cin >> age;

    // Допустимий діапазон віку станції: від 0 до 20 років
    if (age < 0 || age > 20){
        cout << "Недопустимий вік станції" << endl;
        return 1;
    }

    //Ввід та перевірка рівня заряду станції 
    int charge;
    cout << "Введіть рівень заряду станції у %:    ";
    cin >> charge;

    // Рівень заряду може бути тільки від 0 до 100 %
    if (charge < 0 || charge > 100){
        cout << "Недопустимий рівень заряду станції" << endl;
        return 1;
    }

    //  Ввід та перевірка ККД інвертора 
    int eff;
    cout << "Введіть ККД інвертора у %:    ";
    cin >> eff;

    // ККД (коефіцієнт корисної дії) — теж може бути лише від 0 до 100 %
    if (eff < 0 || eff >100){
        cout << "Недопустимий ККД інвертора" << endl;
        return 1;
    }

    //  Ввід та перевірка потужності приладу     
    int P;
    cout << "Введіть потужність приладу у Вт :    ";
    cin >> P;  

    // Потужність не може бути від'ємною і має бути більшою за 0
    if (P < 0){
        cout << "Недопустима потужність приладу" << endl;
        return 1;
    }

    // Оголошення змінних для результатів обчислень
    double C_eff;      // фактична ємність станції з урахуванням її віку, Вт*год
    double E_stored;   // запас енергії при поточному рівні заряду, Вт*год
    double E_useful;   // корисна енергія, що дійде до приладу, Вт*год
    double E_loss;      // втрати енергії на перетворенні напруги в інверторі, Вт*год
    double T;           // час роботи приладу, годин
    int h;               // ціла кількість годин роботи
    int m;               // кількість хвилин роботи понад повні години

    // Крок 1: фактична ємність станції з урахуванням віку, Вт*год.
    // Щороку ємність зменшується на 2%, тому переводимо цей відсоток у частку
    // (2.0 / 100) і підносимо коефіцієнт деградації до степеня "вік станції".
    C_eff = capacity * pow((1 - 2.0 / 100), age);

    // Крок 2: запас енергії при поточному рівні заряду, Вт*год.
    // Переводимо відсоток заряду (charge) у частку від фактичної ємності.
    E_stored = C_eff * charge / 100;

    // Крок 3: корисна енергія, що дійде до приладу, Вт*год.
    // Переводимо ККД інвертора (eff) у частку від запасеної енергії.
    E_useful = E_stored * eff / 100;

    // Крок 4: втрати енергії на перетворенні напруги в інверторі, Вт*год.
    // Це різниця між тим, що було запасено, і тим, що дійшло до приладу.
    E_loss = E_stored - E_useful;

    // Крок 5: час роботи приладу від станції, годин.
    // Ділимо корисну енергію на потужність приладу.
    T = E_useful / P;

    // Крок 6: ціла кількість повних годин роботи (дробова частина відкидається).
    h = T;

    // Крок 7: кількість хвилин, що залишились понад повні години.
    // Беремо дробову частину годин (T - h) і переводимо її у хвилини (*60).
    m = (T - h) * 60;

    //  Вивід результатів обчислень користувачу     
    cout << left << setw(40) << "Модель станції:                 " << ModelStation << "\n";
    cout << left << setw(40) << "Паспортна ємність станції:      " << fixed << setprecision(1) << capacity << " Вт.год\n";
    cout << left << setw(40) << "Вік станції:                    " << fixed << setprecision(0) << age << " р.\n";
    cout << left << setw(40) << "Фактична ємність:               " << fixed << setprecision(1) << C_eff << " Вт.год\n";
    cout << left << setw(40) << "Рівень заряду:                  " << fixed << setprecision(0) << charge << "%\n";
    cout << left << setw(40) << "ККД інвертора:                  " << fixed << setprecision(2) << eff << "%\n";
    cout << left << setw(40) << "Запас енергії:                  " << fixed << setprecision(1) << E_stored << " Вт.год\n";
    cout << left << setw(40) << "Корисна енергія:                " << fixed << setprecision(1) << E_useful << " Вт.год\n";
    cout << left << setw(40) << "Втрати на перетворення:         " << fixed << setprecision(1) << E_loss << " Вт.год\n";

}
