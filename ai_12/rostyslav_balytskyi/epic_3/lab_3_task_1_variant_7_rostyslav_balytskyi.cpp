// Лабораторна робота №3
// Тема: "Обчислення функцій з використанням їхнього розкладу в степеневий ряд"
// Варіант 7: y = cos(x), 0.1 <= x <= 1, n = 10
// Ряд Маклорена для cos x:
//   S = 1 - x^2/2! + x^4/4! - ... + (-1)^n * x^(2n)/(2n)!
// Загальний член:  a_n = (-1)^n * x^(2n) / (2n)!
// Використовуємо рекурентне співвідношення (n! обчислювати напряму не треба):
//   a_0 = 1
//   a_{n+1} = a_n * ( -x^2 / ((2n+1)(2n+2)) )
// Перевірка: a_1 = a_0 * (-x^2 / (1*2)) = -x^2/2!  -- вірно.

#include <iostream>
#include <iomanip>
#include <cmath>

using namespace std;

int main()
{
    const double a = 0.1;        // початок проміжку
    const double b = 1.0;        // кінець проміжку
    const int    k = 10;         // кількість кроків
    const int    N = 10;         // задане n (варіант 7)
    const double eps = 0.0001;   // задана точність
    const double h = (b - a) / k; // крок зміни x = 0.09

    cout << "Обчислення функції y = cos(x)" << endl;
    cout << fixed << setprecision(6);

    // ЗОВНІШНІЙ ЦИКЛ: змінюємо параметр x від a до b з кроком h.
    // Використовуємо лічильник i, щоб уникнути накопичення похибки
    // при додаванні дробового кроку (x += h могло б "не дійти" до b).
    for (int i = 0; i <= k; i++)
    {
        double x = a + i * h;
        double x2 = x * x;       // x^2 обчислюємо один раз

        // ---- а) АРИФМЕТИЧНИЙ ЦИКЛ: сума для заданого n ----
        double term = 1.0;       // a_0 = 1
        double SN = term;        // початкове значення суми
        for (int n = 0; n < N; n++)
        {
            // перехід від a_n до a_{n+1} за рекурентною формулою
            term = term * (-x2) / ((2.0 * n + 1) * (2.0 * n + 2));
            SN += term;
        }

        // ---- б) ІТЕРАЦІЙНИЙ ЦИКЛ: сума із заданою точністю eps ----
        term = 1.0;              // знову починаємо з a_0
        double SE = term;
        int n = 0;
        // додаємо члени, поки модуль наступного члена >= eps
        while (true)
        {
            term = term * (-x2) / ((2.0 * n + 1) * (2.0 * n + 2));
            n++;
            if (fabs(term) < eps)  // умова зупинки: |a_n| < eps
                break;
            SE += term;
        }

        // Точне значення функції для порівняння
        double Y = cos(x);

        cout << "X=" << x << "  SN=" << SN
             << "  SE=" << SE << "  Y=" << Y << endl;
    }

    return 0;
}