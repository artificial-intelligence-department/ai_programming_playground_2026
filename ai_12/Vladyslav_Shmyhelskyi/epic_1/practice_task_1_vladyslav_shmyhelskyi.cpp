    cout << "Паспортна ємність (Вт·год): ";
    cin >> c;
    if (c <= 0)
    {
        cout << "Паспортна ємність повинна бути більше 0";
        return 1; // Встановлення умови, яка обмежує паспортну ємність станції//
    }

    int years; // Створення цілочисельної змінної для введення віку станції//
    cout << "Вік станції (років): ";
    cin >> years;
    if (years < 0 || years > 20)
    {
        cout << "Вік станції повинен бути від 0 до 20 років";
        return 1;
    }

    double charge;
    cout << "Рівень заряду (%): ";
    cin >> charge;
    if (charge < 0 || charge > 100)
    {
        cout << "Рівень заряду повинен бути від 0 до 100%";
        return 1;
    }

    double eff;
    cout << "ККД інвертора (%): ";
    cin >> eff;
    if (eff < 0 || eff > 100)
    {
        cout << "ККД інвертора повинно бути від 0 до 100";
        return 1;
    }

