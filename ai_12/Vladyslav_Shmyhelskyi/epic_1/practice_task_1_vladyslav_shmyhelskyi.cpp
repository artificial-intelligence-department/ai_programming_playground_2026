    // Обчислення при поточному рівні заряду//

    double E_useful = E_stored * eff / 100.0;
    // Обчислення корисного обсягу енергії,що дійде до приладу//

    double E_loss = E_stored - E_useful;
    // Обчислення втрати енергії під час перетворення//

    double T = E_useful / P;
