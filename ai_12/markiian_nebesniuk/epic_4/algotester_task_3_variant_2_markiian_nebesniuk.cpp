#include <iostream>
using namespace std;

int main() {
    // Створюємо масиви із запасом
    int a[200];
    int b[200];
    // Зчитуємо перший масив
    int N;
    cin >> N;
    for (int i = 0; i < N; i++) {
        cin >> a[i];
    }

    // Зчитуємо другий масив
    int M;
    cin >> M;
    for (int i = 0; i < M; i++) {
        cin >> b[i];
    }

    // Лічильник однакових елементів в обох масивах
    int k = 0;
    // Вкладені цикли для пошуку перетину: перевіряємо кожен елемент a[i] з кожним b[j]
    for (int i = 0; i < N; i++) {
        for (int j = 0; j < M; j++) {
            if (a[i] == b[j]) k++;
        }
    }
    
    // Виводимо кількість елементів, наявних в обох масивах (перетин)
    cout << k << endl;
    
    // Виводимо кількість унікальних елементів разом (об'єднання)
    cout << N + M - k << endl;
}