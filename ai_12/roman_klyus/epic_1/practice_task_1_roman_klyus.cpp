#include <iostream>
#include <string>
#include <cmath>
#include <iomanip>

using namespace std;

int main() {
    // Оголошуємо змінні, щоб на них виділилася пам'ять.
    // string - текст.
    // double - число з плаваючою комою.
    // int - ціле число
    string model;
    double capacity;
    int years;
    int charge;
    double eff;
    double power;

    // Відсоток річного зниження ємності акумулятора через старіння
    const double degradation = 2.0;

    // Зчитування вхідних даних із перевіркою коректності та виходом у разі помилки

    // Робимо перевірку у два етапи: !(cin >> змінна) виявляє помилку типу даних (наприклад, введення літер),
    // а друга частина умови перевіряє чи відповідвають введені дані обмеженням задачі.

    // Зчитування назви моделі: довжина назви моделі має бути меншою за 31 символ
    cout << "Модель станції:";
    if (!(cin >> model) || model.length() > 31) { 
        cout << "Помилка: неправильно вказана модель станції." << endl;
        return 1; // Завершення програми з кодом помилки
    }
    
    // Зчитування паспортної ємності: ємність акумулятора строго має бути додатним числом (> 0)
    cout << "Паспортна ємність (Вт·год):";
    if (!(cin >> capacity) || capacity <= 0) { 
        cout << "Помилка: паспортна ємність має бути числом, більшим за нуль." << endl;
        return 1;
    }

    // Зчитування віку: допустимий термін експлуатації станції за умовою задачі від 0 до 20 років включно
    cout << "Вік станції (років):";
    if (!(cin >> years) || years < 0 || years > 20) { 
        cout << "Помилка: вік станції має бути числом від 0 до 20." << endl;
        return 1;
    }

    // Зчитування рівня заряду: відсоток заряду акумулятора фізично знаходиться в межах від 0% до 100% включно
    cout << "Рівень заряду (%):";
    if (!(cin >> charge) || charge < 0 || charge > 100) { 
        cout << "Помилка: рівень заряду має бути числом від 0 до 100." << endl;
        return 1;
    }
    
    // Зчитування ККД інвертора: ККД має бути більшим за 0% та не перевищувати 100%
    cout << "ККД інвертора (%):";
    if (!(cin >> eff) || eff <= 0 || eff > 100) { 
        cout << "Помилка: ККД інвертора має бути більше 0 та не більше 100." << endl;
        return 1;
    }

    // Зчитування потужності споживача: потужність приладу має бути строго додатним числом (> 0)
    cout << "Потужність приладу (Вт):";
    if (!(cin >> power) || power <= 0) { 
        cout << "Помилка: потужність приладу має бути більше 0." << endl;
        return 1;
    }

    // Обчислюємо фактичну ємність враховуючи деградацію
    double c_eff = capacity * pow(1.0 - degradation / 100.0, years);

    // Рахуємо скільки енергії в нас є при поточному заряді
    double e_stored = c_eff * (charge / 100.0);

    // Враховуємо ККД інвертора і знаходимо корисну енергію
    double e_useful = e_stored * (eff / 100.0);

    // Знаходимо скільки енергії втрачається на перетворенні
    double e_loss = e_stored - e_useful;

    // Рахуємо загальний час работы приладу в годинах
    double time = e_useful / power;

    // Забираємо цілу частину годин, використовуємо static_cast<int>, щоб змінити тип даних з double на int
    int hours = static_cast<int>(time);

    // Переводимо дробовий залишок годин у хвилини, аналогічно
    int minutes = static_cast<int>((time - hours) * 60.0);

    // Форматуємо вивід результатів, щоб зробити табличний вигляд та оптимізувати блок-схему
    // Форматуємо вивід результатів в один cout (щоб не роздувати блок-схему).
    // Маніпулятори форматування з бібліотеки <iomanip>:
    // right — вирівнює значення по правому краю у виділеній точці.
    // setw(8) — виділяє фіксовану ширину в 8 символів для числа, щоб одиниці виміру йшли строго в колонку.
    // fixed — виводить дробові числа у звичайному форматі (не через e+02).
    // setprecision(N) — задає кількість знаків після коми (1 або 2).
    // setfill('0') — дописує '0' попереду (наприклад, щоб хвилин було "05", а не " 5"), а в кінці скидаємо setfill жо дефолтного значення.
    cout << "\n"
         << "Модель:                 " << model << "\n"
         << "Паспортна ємність:      " << right << setw(8) << fixed << setprecision(1) << capacity << " Вт·год\n"
         << "Вік станції:            " << right << setw(8) << years << " р.\n"
         << "Фактична ємність:       " << right << setw(8) << fixed << setprecision(1) << c_eff << " Вт·год\n"
         << "Рівень заряду:          " << right << setw(8) << charge << "%\n"
         << "ККД інвертора:          " << right << setw(8) << fixed << setprecision(2) << eff << "%\n"
         << "Запас енергії:          " << right << setw(8) << fixed << setprecision(1) << e_stored << " Вт·год\n"
         << "Корисна енергія:        " << right << setw(8) << fixed << setprecision(1) << e_useful << " Вт·год\n"
         << "Втрати на перетворенні: " << right << setw(8) << fixed << setprecision(1) << e_loss << " Вт·год\n"
         << "Час роботи:             " << right << setw(8) << fixed << setprecision(2) << time << " год = " 
         << hours << " год " << setfill('0') << setw(2) << minutes << " хв" << setfill(' ') << endl;

    return 0;
}