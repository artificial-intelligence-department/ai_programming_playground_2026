#include <iostream>

using namespace std;

int main(){

    int n; // кількість елементів кільця

    cin >> n;

    int* r = new int[n]; // кільце 

    int k,f,l; // k - номер к елемента, f - новий перший, l - новий останній

    for (int i = 0; i < n; i++){ //  заповнюємо кільце
        cin >> r[i];
    }

    cin >> k;
    k--; // переходимо до нумерації з 0

    for (int i = 0; i < n; i++){ // друк від к елемента вліво по кільцю
        if (i > 0) { cout << " ";}
        cout << r[(k - i + n) % n]; // крок назад, від першого переходимо до останнього, тому ділимо з остачею
    }
    cout << endl;

    cin >> f >> l; // перший і останній елементи, які додаємо

    int* t = new int[n + 2]; // нове кільце, на 2 елементи більше

    t[0] = f; // новий перший елемент

    for (int i = 0; i < n; i++){
        t[i + 1] = r[i]; // копіюємо старі елементи зі зсувом на 1
    }

    t[n + 1] = l; // новий останній елемент

    delete[] r; // звільняємо старий масив
    r = t;
    n += 2;

    for (int i = 0; i < n; i++){ // друк від к елемента вправо по кільцю
        if (i > 0) { cout << " ";}
        cout << r[(k + i) % n]; // крок вперед, від останнього переходимо до першого
    }

    delete[] r; // звільняємо пам'ять

return 0;
}