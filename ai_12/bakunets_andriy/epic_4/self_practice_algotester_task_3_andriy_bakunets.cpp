#include <iostream>

using namespace std;

int main(){

    int n,k;
    int answer = 0;
    cin >> n >> k;

    for (int i = 2; i <= n; i++){ // Рекурентна формула, беремо минулі кола, результат яких уже відомий
        answer = (answer + k) % i; // Беремо минулу відповідь додаємо щасливе число і перевіряємо на остачу від ділення від кількості ворогів
    }

    cout << answer+1; // Виводимо +1 бо в формулі ми починаємо з 0

return 0;
}
