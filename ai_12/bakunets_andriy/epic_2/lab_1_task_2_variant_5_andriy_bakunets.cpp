#include <iostream>

using namespace std;

int main() {
    int n, m;

    cout << "Введіть значення n: ";
    cin >> n;
    cout << "Введіть значення m: ";
    cin >> m;

    cout << "\nРезультати обчислень:" << endl;

    // Вираз: - -m-++n
    int n1 = n, m1 = m;
    int res1 = - -m1 - ++n1;
    cout << "1) - -m-++n = " << res1 
         << " (після обчислення: n = " << n1 << ", m = " << m1 << ")" << endl;

    // Вираз: m*n < n++
    int n2 = n, m2 = m;
    bool res2 = (m2 * n2 < n2++);
    cout << "2) m*n < n++ = " << boolalpha << res2 
         << " (після обчислення: n = " << n2 << ", m = " << m2 << ")" << endl;

    // Вираз: n-- > m++
    int n3 = n, m3 = m;
    bool res3 = (n3-- > m3++);
    cout << "3) n-- > m++ = " << boolalpha << res3 
         << " (після обчислення: n = " << n3 << ", m = " << m3 << ")" << endl;

    return 0;
}

/*
1) Вираз `- -m-++n`:
   - `++n` — префіксний інкремент, який спочатку збільшує значення n на 1, 
     і лише потім бере участь у відніманні.
   - `- -m` — два послідовних унарних мінуси, які в результаті дають початкове додатне значення m.
   - Підсумкова формула: m - (n + 1).

2) Вираз `m*n < n++`:
   - Спочатку обчислюється добуток m * n з початковими значеннями.
   - `n++` — постфіксний інкремент, тому для порівняння береться поточне (початкове) значення n, 
     а саме збільшення n на 1 відбувається вже після порівняння.
   - Результат порівняння є логічним (true або false).

3) Вираз `n-- > m++`:
   - Обидва оператори (n-- та m++) є постфіксними.
   - Для порівняння використовуються початкові введені значення n та m.
   - Після виконання порівняння n зменшується на 1 (декремент), а m збільшується на 1 (інкремент).
   - Результат порівняння є логічним (true або false).
*/