#include <iostream>
#include <cmath>
#include <iomanip>

using namespace std;

int main() {
    // Оголошення змінних для вводу
    string model;
    double C, eff, P;
    int years, charge;
/*Ввід усіх величин. Тут у if йде перевірка на помилки при вводі,
та за наявності помилки виконання коду завершується.
Наприклад тут перевірка на довжину моделі (не більше 31 символу),
fail() перевіряє, чи не було помилки під час введення (наприклад, якщо користувач ввів літери замість числа)
return 1 завершує виконання програми з кодом помилки 1
*/
    cout << "Модель станції: ";
    cin >> model;

    // Перевірка назви моделі
    
    if (cin.fail() || model.length() > 31) {
        cout << "Помилка, назва моделі має становити менше 32 символів!\n";
        return 1;
    }

    cout << "Паспортна ємність (Вт x год, > 0): ";
    cin >> C;

    // Перевірка ємності
    if (cin.fail() || C <= 0) {
        cout << "Помилка! Значення ємності має бути більше 0.\n";
        return 1;
    }

    cout << "Вік станції (років, 0-20): ";
    cin >> years;

    // Перевірка віку
    if (cin.fail() || years < 0 || years > 20) {
        cout << "Помилка! Вік має бути від 0 до 20 років.\n";
        return 1;
    }

    cout << "Рівень заряду (%, 0-100): ";
    cin >> charge;

    // Перевірка заряду
    if (cin.fail() || charge < 0 || charge > 100) {
        cout << "Помилка! Заряд має бути від 0 до 100%.\n";
        return 1;
    }

    cout << "ККД інвертора (%, > 0, <= 100): ";
    cin >> eff;

    // Перевірка ККД
    if (cin.fail() || eff <= 0 || eff > 100) {
        cout << "Помилка! ККД має бути більше 0 і не більше 100%.\n";
        return 1;
    }

    cout << "Потужність приладу (Вт, > 0): ";
    cin >> P;

    // Перевірка потужності
    if (cin.fail() || P <= 0) {
        cout << "Помилка! Потужність має бути більше 0.\n";
        return 1;
    }

    // Оголошення змінних для обчислень
    float C_eff, E_stored, E_useful, E_loss, T;
    int h, m;

    // Обчислюємо фактичну ємність з урахуванням втрати 2% за рік
    C_eff = C * pow(1 - 2.0 / 100, years);

    // Обчислюємо запас енергії при поточному рівні заряду
    E_stored = C_eff * charge / 100;

    // Обчислюємо корисну енергію після втрат в інверторі
    E_useful = E_stored * eff / 100;

    // Обчислюємо втрати енергії під час перетворення
    E_loss = E_stored - E_useful;

    // Обчислюємо час роботи приладу
    T = E_useful / P;

    // Визначаємо повну кількість годин
    h = int(T);

    // Визначаємо кількість хвилин після повних годин
    m = int((T - h) * 60);

    // Вивід результатів
    cout << "\n";
    cout << "Модель:                 " << model << "\n";

    cout << fixed << setprecision(1);
    cout << "Паспортна ємність:      " << C << " Вт x год\n";

    cout << "Вік станції:            " << years << " р.\n";

    cout << "Фактична ємність:       " << C_eff << " Вт x год\n";

    cout << "Рівень заряду:          " << charge << " %\n";

    cout << fixed << setprecision(2);
    cout << "ККД інвертора:          " << eff << " %\n";

    cout << fixed << setprecision(1);
    cout << "Запас енергії:          " << E_stored << " Вт x год\n";
    cout << "Корисна енергія:        " << E_useful << " Вт x год\n";
    cout << "Втрати на перетворенні: " << E_loss << " Вт x год\n";

    // Форматування часу
    cout << fixed << setprecision(2);
    cout << "Час роботи:             " << T << " год = " << h << " год " << setw(2) << setfill('0') << m << " хв\n";

    return 0;
}