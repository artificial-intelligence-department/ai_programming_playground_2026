#include <iostream>
using namespace std;

int main() {
    // початкові хітпойнти (H) та мана (M) персонажа
    // за умовою можуть сягати 10^12, тому long long обов'язково
    long long H, M;
    cin >> H >> M;

    // прапорець програшу: стає true, якщо хоч одне закляття
    // одночасно забирає і хітпойнти, і ману
    bool lose = false;

    // персонаж використовує рівно 3 закляття
    for (int i = 0; i < 3; i++) {
        long long h, m;   // скільки хітпойнтів (h) і мани (m) забирає це закляття
        cin >> h >> m;

        // правило програшу: закляття не може забирати
        // і хп, і ману одночасно
        if (h > 0 && m > 0) {
            lose = true;
        }

        // незалежно від правила витрачаємо ресурси,
        // щоб коректно порахувати фінальний стан персонажа
        H -= h;
        M -= m;
    }

    // персонаж виграє, лише якщо:
    // 1) жодне закляття не порушило правило (не було lose)
    // 2) в кінці і хітпойнти, і мана строго додатні (>0)
    if (lose || H <= 0 || M <= 0) {
        cout << "NO" << endl;
    } else {
        cout << "YES" << endl;
    }

    return 0;
}
