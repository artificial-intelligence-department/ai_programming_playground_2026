#include <iostream>
using namespace std;
 
int main() 
{
    const int MAX=100;
    int a[MAX],n,k,i,elem1;
    cout<<"Введіть кількість елементів масиву(1-100): ";
    cin>>n;
    cout<<"Введіть елементи масиву: ";
    for(i=0;i<n;i++)
    cin>>a[i];
    cout<<"Введіть k для виведення масив по кільцю вліво: ";
    cin>>k;
    k=k-1;
    i=k;
    int c;
    cout<<"Масив по кільцю вліво: ";
    for(c=0;c<n;c++)
    {
        cout<<a[i]<<" ";
        i=i-1;
        if(i<0)i=n-1;
    }
    cout<<endl;
    cout<<"Введіть який елемент додати першим: ";
    cin>>elem1;
    for(i=n-1;i>=0;i--)
    {
        a[i+1]=a[i];
    }
    a[0]=elem1;
    n=n+1;
    cout<<"Введіть які 3 елементи додати в кінці: ";
    cin>>a[n]>>a[n+1]>>a[n+2];
    n=n+3;
    cout<<"Введіть k для виведення масив по кільцю вправо: ";
    cin>>k;
    i=k-1;
    cout<<"Масив по кільцю вправо: ";
    for(c=0;c<n;c++)
    {
        cout<<a[i]<<" ";
        i++;
        if(i>n-1)i=0;
    }
}