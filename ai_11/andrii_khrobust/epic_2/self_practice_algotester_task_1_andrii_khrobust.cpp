#include <iostream>
using namespace std;

int main() {
    int n;//кількість рядків шоколадки
    int m; //кількість стовпців шоколадки
    int k;//кількість друзів
    cin >> n >> m >> k;

    if ((n * m) % k == 0) {//якщо зеник зміг порівну поділити шоколадку
        cout << "Yes" << endl;
    }
    else {//якщо не зміг
        cout << "No" << endl;
    }

    return 0;
}
