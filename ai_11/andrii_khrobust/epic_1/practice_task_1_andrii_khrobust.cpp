#include <iostream>
#include <iomanip>
#include <string>
#include <cmath>

using namespace std;

int main() {
const double D = 2.0; // відсоток втрати ємності за рік.
string model;
double C, eff, P;
int years, charge;// змінні
cout << "Модель станції(одним словом): ";// Модель станції: одне слово без пробілів, не довше 31 символа 
cin >>model;
if (model.length() > 31) {
    cout << "Помилка: назва моделі не повинна перевищувати 31 символ." << endl;
    return 1;
}
cout << "Паспортна ємність (Вт*год): ";// Паспортна ємність, Вт*год: число, більше 0
cin >> C;
if (cin.fail() || C <= 0) {
    cout << "Помилка: паспортна ємність має бути додатним числом." << endl;
    return 1;
}
cout << "Вік станції (років): ";// Вік станції, років: ціле число від 0 до 20
cin >> years;

if (cin.fail() || years < 0 || years > 20) {
    cout << "Помилка: вік станції мусить бути від 0 до 20." << endl;
    return 1;
}
cout << "Рівень заряду (%): ";// Рівень заряду, %: ціле число від 0 до 100
cin >> charge;

if (cin.fail() || charge < 0 || charge > 100) {
    cout << "Помилка: рівень заряду мусить бути від 0 до 100." << endl;
    return 1;
}
cout << "ККД інвертора (%): ";// ККД інвертора, %: число, більше 0, не більше 100
cin >> eff;

if (cin.fail() || eff <= 0 || eff > 100) {
    cout << "Помилка: ККД інвертора має бути більше 0 і не більше 100." << endl;
    return 1;
}
cout << "Потужність приладу (Вт): ";// Потужність приладу, Вт: число, більше 0 
cin >> P;

if (cin.fail() || P <= 0) {
    cout << "Помилка: потужність приладу має бути додатним числом." << endl;
    return 1;
}
double C_eff = C * pow(1.0 - D / 100.0, years);/* Крок 1: фактична ємність з урахуванням віку станції, Вт*год. Щороку ємність зменшується на D відсотків від 
попереднього значення, тому множимо паспортну ємність на (1 - 2/100) у степені кількості років (при years = 0 ємність дорівнює паспортній).*/
double E_stored = C_eff * charge / 100.0;// Крок 2: запас енергії при поточному рівні заряду, Вт*год. Переводимо відсотки заряду у частку від фактичної ємності.
double E_useful = E_stored * eff / 100.0;// Крок 3: корисна енергія, що дійде до приладу, Вт*год.Враховуємо втрати при перетворенні напруги в інверторі (ККД у частку).
double E_loss = E_stored - E_useful;// Крок 4: втрати енергії на перетворенні напруги в інверторі, Вт*год.
double T = E_useful / P;// Крок 5: час роботи приладу від станції, годин.
int h = static_cast<int>(T);// Крок 6: кількість повних годин роботи (ціла частина часу).
int m = static_cast<int>((T - h) * 60.0);// Крок 7: кількість хвилин понад повні години (залишок часу у хвилинах).
cout << fixed << endl;//Виведення результатів
cout << setw(23) << "Модель:";
cout << right << setw(23) << model << endl;
cout << setprecision(1);
cout << setw(23) << "Паспортна ємність:";
cout<< right << setw(23) << C << " Вт*год" << endl;
cout << setprecision(0);
cout << setw(23) << "Вік станції:";
cout<< right << setw(23) << years << " р." << endl;
cout << setprecision(1);
cout << setw(23) << "Фактична ємність:";
cout<< right << setw(23) << C_eff << " Вт*год" << endl;
cout << setprecision(0);
cout << setw(23) << "Рівень заряду:";
cout<< right << setw(23) << charge << " %" << endl;
cout << setprecision(2);
cout << setw(23) << "ККД інвертора:";
cout<< right << setw(23) << eff << " %" << endl;
cout << setprecision(1);
cout << setw(23) << "Запас енергії:";
cout<< right << setw(23) << E_stored << " Вт*год" << endl;
cout << setw(23) << "Корисна енергія:";
cout<< right << setw(23) << E_useful << " Вт*год" << endl;
cout << setw(23) << "Втрати на перетворенні:";
cout<< right << setw(23) << E_loss << " Вт*год" << endl;
cout << setprecision(2);
cout << setw(23) << "Час роботи:";
cout<< right << setw(23) << T << " год = " << h << " год " << setfill('0') << setw(2) << m << " хв" << endl;
return 0;
}