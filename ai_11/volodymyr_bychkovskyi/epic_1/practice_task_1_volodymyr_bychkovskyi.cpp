#include <iostream>  // Введення та виведення даних
#include <clocale>   // Налаштування мови 
#include <string>    // Робота з текстовими даними
#include <cmath>     // Виконання математичних обчислень
#include <iomanip>   // Точне форматування дробових чисел

using namespace std; // Підключення стандартного простору імен


int main() {
    // Налаштування локалізації для коректного відображення українських символів
    setlocale(LC_ALL, "uk_UA");

    // Відсоток щорічної втрати ємності акумулятора (2%)
    int LOSED_Capacity = 2; 

    // Оголошення змінних для вхідних даних та результатів
    string model_name;
    double C;          // Паспортна ємність 
    int years;         // Вік станції 
    int charge;        // Рівень заряду 
    double eff;        // ККД інвертора 
    int P;             // Потужність споживача 
    
    double C_eff;      // Фактична ємність з урахуванням зносу 
    double E_stored;   // Запас енергії при поточному заряді 
    double E_useful;   // Корисна енергія з урахуванням ККД 
    double E_loss;     // Втрати енергії при перетворенні 
    double T;          // Загальний час роботи 
    int h;             // Цілі години
    int mi;            // Хвилини

    // Ввід та перевірка даних
    
// Ввід назви моделі станції
    cout << "Модель станції: ";
    cin >> model_name;
    // Перевірка обмеження довжини назви (до 31 символу)
    if (model_name.length() > 31) {
        cout << "Помилка: Модель станції не може перевищувати 31 символ." << endl;
        return 1; 
    }

    // Ввід паспортної ємності
    cout << "Паспортна ємність, (Вт·год): ";
    cin >> C; 
    // Перевірка, щоб ємність була невід'ємною
    if (C < 0) {
        cout << "Помилка: Паспортна ємність не може бути від'ємною." << endl;
        return 1; 
    }
    
    // Ввід віку станції
    cout << "Вік станції, (років): ";
    cin >> years;
    // Перевірка допустимого діапазону віку (0–20 років)
    if (years < 0 || years > 20) {
        cout << "Помилка: Вік станції не може бути від'ємним та більшим за 20." << endl;
        return 1; 
    }

    // Ввід поточного рівня заряду
    cout << "Рівень заряду, (%): ";
    cin >> charge;
    // Перевірка коректності відсотка заряду (0–100%)
    if (charge < 0 || charge > 100) {
        cout << "Помилка: Рівень заряду не може бути від'ємним та більшим за 100." << endl;
        return 1; 
    }

    // Ввід коефіцієнта корисної дії (ККД) інвертора
    cout << "ККД інвертора, (%): ";
    cin >> eff;
    // Перевірка коректності відсотка ККД (0–100%)
    if (eff < 0 || eff > 100) {
        cout << "Помилка: ККД інвертора не може бути від'ємним та більшим за 100." << endl;
        return 1; 
    }

    // Ввід споживаної потужності приладу
    cout << "Потужність приладу, (Вт): ";
    cin >> P;
    // Перевірка, щоб потужність була строго більше 0 Вт
    if (P <= 0) {
        cout << "Помилка: Потужність повинна бути більшою за 0 Вт." << endl;
        return 1;
    }

    //Обчислення

    // Обчислення фактичної ємності з урахуванням щорічної втрати (2% на рік)
    C_eff = (C * (pow((1 - LOSED_Capacity / 100.0), years)));

    // Обчислення наявного запасу енергії 
    E_stored = C_eff * charge / 100.0;

    // Обчислення корисної енергії, яка дійде до приладу
    E_useful = E_stored * eff / 100.0;

    // Обчислення втрат енергії
    E_loss = E_stored - E_useful;

    // Розрахунок часу автономної роботи
    T = E_useful / P;                      // Час у десятковому форматі 
    h = static_cast<int>(T);              // Виділення цілої кількості годин
    mi = static_cast<int>((T - h) * 60);  // Переведення залишку години у хвилини

    //Виведення результатів

    cout << "Модель станції:                         " << model_name << endl;
    cout << "Паспортна ємність:                      " << fixed << setprecision(1) << C << " Вт·год" << endl;
    cout << "Вік станції:                            " << years << " р." << endl;
    cout << "Фактична ємність:                       " << fixed << setprecision(1) << C_eff << " Вт·год" << endl;
    cout << "Рівень заряду:                          " << charge << " %" << endl;
    cout << "ККД інвертора:                          " << fixed << setprecision(2) << eff << " %" << endl;
    cout << "Запас енергії:                          " << fixed << setprecision(1) << E_stored << " Вт·год" << endl;
    cout << "Корисна енергія:                        " << fixed << setprecision(1) << E_useful << " Вт·год" << endl;
    cout << "Втрати на перетворенні:                 " << fixed << setprecision(1) << E_loss << " Вт·год" << endl;
    cout << "Час роботи:                             " << fixed << setprecision(2) << T << " год = " << h << " год " << setfill('0') << setw(2) << mi << " хв" << endl;
    return 0;   
}