#include<iostream>
using namespace std;

int main() {

    short n, m;

    cout << "Введіть ціле значення n: "; cin >> n;
    cout << "Введіть ціле значення m: "; cin >> m;

    //Створення констант для зручного оперування вхідними даними
    const short n0 = n;
    const short m0 = m;
    
    cout << "\n1) n---m\n";
    cout << "Значення до обчислення: n = " << n0 << ", m = " << m0 << endl;

    cout << "Перший варіант (n-- - m): \n";
    n--; //Знаходимо n-1, щоб далі використовувати його в розрахунках
    cout << "Результат: " << n - m0 << endl;
    cout << "Значення після обчислення: n = " << n << ", m = " << m0 << endl;

    cout << "Другий варіант (n - --m): \n";
    --m; //Знаходимо m-1, щоб далі використовувати його в розрахунках
    cout << "Результат: " << n0 - m << endl;
    cout << "Значення після обчислення: n = " << n0 << ", m = " << m << endl;

    //Передаємо змінним n і m їх вхідні дані
    n = n0;
    m = m0;

    cout << "\n2) m--<n\n";
    cout << "Значення до обчислення: n = " << n0 << ", m = " << m0 << endl;

    m--; //Знаходимо m-1, щоб далі використовувати його в розрахунках
    if (m<n) cout << "Результат: True\n" << "Значення після обчислення: n = " << n << ", m = " << m << endl;
    else cout << "Результат: False\n" << "Значення після обчислення: n = " << n << ", m = " << m << endl;

    //Передаємо змінним n і m їх вхідні дані
    n = n0;
    m = m0;

    cout << "\n3) n++>m\n";
    cout << "Значення до обчислення: n = " << n0 << ", m = " << m0 << endl;

    n++; //Знаходимо n+1, щоб далі використовувати його в розрахунках
    if (n>m) cout << "Результат: True\n" << "Значення після обчислення: n = " << n << ", m = " << m << endl;
    else cout << "Результат: False\n" << "Значення після обчислення: n = " << n << ", m = " << m << endl;

    return 0;
}