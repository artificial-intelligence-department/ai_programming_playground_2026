//суть завдання Є послідовність, як у Фібоначчі: кожне наступне число дорівнює сумі двох попередніх треба визначити нахил гойдалки а саме знак першого числа
//n — це номер місця в ряду, про яке питають.
#include <cstdio>

int main() {
    long long n, p, c;          //користовач водить дані
    scanf("%lld %lld %lld", &n, &p, &c);

//перевіряємо початковий момент
    if (n == 0) {             
        if (p > 0) printf("+\n");
        else if (p < 0) printf("-\n");
        else printf("0\n");
        return 0;
    }


    for (long long i = 1; i < n; i++) {
        if (p == 0 && c == 0) { printf("0\n"); return 0; }//Якщо обидва нулі то далі самі нулі
        if (p >= 0 && c >= 0) { printf("+\n"); return 0; }
        if (p <= 0 && c <= 0) { printf("-\n"); return 0; }//Якщо обидва непозитивні то все далі від'ємне
        long long x = p + c;    // знаки різні — рахуємо далі
        p = c;
        c = x;
    }
//вивід на випадок коли цикл цикилився або n = 1 
    if (c > 0) printf("+\n");  
    else if (c < 0) printf("-\n");
    else printf("0\n");
    return 0;
}