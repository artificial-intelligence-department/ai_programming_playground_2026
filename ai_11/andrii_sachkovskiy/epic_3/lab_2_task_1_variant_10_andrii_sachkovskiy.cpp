#include <iostream>
#include <iomanip>
using namespace std;

int main()
{
    /*
        Загальний член ряду:

                  n!
        a(n) = --------
                (2n)!

        Рекурентна формула (виведена як відношення a(n+1) / a(n)):

                     (n+1)!         (2n)!             (n+1)             1
        a(n+1)/a(n) = -------- * ------- = ---------------------- = ----------
                     (2n+2)!         n!       (2n+2)(2n+1)           2(2n+1)

        Тобто:

                              1
        a(n+1) = a(n) * ------------
                          2 * (2n+1)

        Перший член:

                  1!     1
        a(1) = ------ = ---  = 0.5
                  2!     2
    */

    const double e = 0.0001;   
    double a = 0.5;            // a(1) = 1!/2!
    double suma = a;          
    int n = 1;               

    // додаємо наступні члени доки поточний член не стане меншим за e
    while (a >= e)
    {
        a = a / (2.0 * (2 * n + 1));   // a(n+1) = a(n) / (2(2n+1))
        suma += a;
        n++;
    }

    cout << "Сума ряду: " << fixed << setprecision(4) << suma << endl;
    return 0;
}