#include <iostream>
#include <iomanip>
#include <cmath>
#include <string>

using namespace std;

int main()
{

    string model; // Модель станції
    double C;     // Паспортна ємність, Вт·год
    int years;    // Вік станції, років
    int charge;   // Рівень заряду, %
    double eff;   // ККД інвертора, %
    double P;     // Потужність приладу, Вт

    const double degradation = 1.0 - 2.0 / 100.0;
    // Розрахунок коефіцієнта збереження ємності після щорічної втрати 2%

    // Введення моделі станції
    cout << "Модель станції:" << endl;
    getline(cin, model);
    if (model.length() > 31) {
        cout << "Модель має бути меньше 31 символів." << endl;
        return 1;
    }
    for (char space : model) {
        if (space == ' ') {
            cout << "Модель не повинна містити пробілів." << endl;
            return 1;
        }
    }

    // Введення паспортної ємності станції у Вт·год
    cout << "Паспортна ємність (Вт·год)" << endl;
    if (!(cin >> C))
    {
        cout << "Помилка: Паспортна ємність має бути числом." << endl;
        return 1;
    }
    if (C <= 0)
    {
        cout << "Помилка: Паспортна ємність має бути більше 0." << endl;
        return 1;
    }

    // Введення віку станції у роках
    cout << "Вік станції (років)" << endl;
    if (!(cin >> years))
    {
        cout << "Помилка: Вік станції має бути числом." << endl;
        return 1;
    }
    if (years < 0 || years > 20)
    {
        cout << "Помилка: Вік станції має бути від 0 до 20." << endl;
        return 1;
    }

    // Введення поточного рівня заряду у відсотках
    cout << "Рівень заряду (%)" << endl;
    if (!(cin >> charge))
    {
        cout << "Помилка: Рівень заряду має бути числом." << endl;
        return 1;
    }
    if (charge < 0 || charge > 100)
    {
        cout << "Помилка: Рівень заряду має бути від 0 до 100." << endl;
        return 1;
    }

    // Введення ККД інвертора у відсотках
    cout << "ККД інвертора (%)" << endl;
    if (!(cin >> eff))
    {
        cout << "Помилка: ККД інвертора має бути числом." << endl;
        return 1;
    }
    if (eff < 0 || eff > 100)
    {
        cout << "Помилка: ККД інвертора має бути від 0 до 100." << endl;
        return 1;
    }

    // Введення потужності приладу у Вт
    cout << "Потужність приладу (Вт)" << endl;
    if (!(cin >> P))
    {
        cout << "Помилка: Потужність має бути числом." << endl;
        return 1;
    }
    if (P <= 0)
    {
        cout << "Помилка: Потужність має бути більше 0." << endl;
        return 1;
    }

    // Обчислюємо фактичну ємність станції з урахуванням її віку (Вт·год)
    double C_eff = C * pow(degradation, years);

    // Обчислюємо запас енергії при поточному заряді (Вт·год)
    double E_stored = C_eff * charge / 100;

    // Обчислюємо корисну енергію що дійде до приладу (Вт·год)
    double E_useful = E_stored * eff / 100;

    // Обчислюємо втрати на перетворенні напруги (Вт·год)
    double E_loss = E_stored - E_useful;

    // Обчислюємо час роботи (годин)
    double T = E_useful / P;

    // Визначаємо повну кількість годин роботи
    int h = static_cast<int>(T);

    // Визначаємо кількість хвилин, що залишилися після повних годин
    int m = static_cast<int>((T - h) * 60);

    // Виводимо результати з потрібною точністю
    cout << fixed << setprecision(1); //  1 знак після коми
    cout << "\nМодель: " << model << endl;
    cout << "Паспортна ємність: " << C << " Вт·год" << endl;
    cout << "Вік станції: " << years << " p." << endl;
    cout << "Фактична ємність: " << C_eff << " Вт·год" << endl;
    cout << "Рівень заряду: " << charge << " %" << endl;

    cout << fixed << setprecision(2); //  2 знака після коми
    cout << "ККД інвертора: " << eff << " %" << endl;

    cout << fixed << setprecision(1); //  1 знак після коми
    cout << "Запас енергії: " << E_stored << " Вт·год" << endl;
    cout << "Корисна енергія: " << E_useful << " Вт·год" << endl;
    cout << "Втрати на перетворенні: " << E_loss << " Вт·год" << endl;

    cout << fixed << setprecision(2); //  2 знака після коми
    cout << "Час роботи: " << T << " год = " << h << " год " << setfill('0') << setw(2) << m << " хв" << endl;

    return 0;
}
