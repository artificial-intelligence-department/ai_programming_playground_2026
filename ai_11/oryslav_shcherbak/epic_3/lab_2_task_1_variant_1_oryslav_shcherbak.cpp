int main(){
    int sum = 0; // сума чисел
    // перебираємо числа від 0 до 199 з кроком 3
    for (int i = 0; i < 200; i +=3){
        sum += i; // додаємо поточне число до суми
    }
    // виводимо результат
    cout << sum << endl;
    return 0;
}