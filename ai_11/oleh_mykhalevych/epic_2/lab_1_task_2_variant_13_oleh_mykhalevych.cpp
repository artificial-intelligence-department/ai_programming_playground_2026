#include <iostream>

int main() {
    int n = 0;
    int m = 0;

    std::cout << "Введіть початкове значення n: ";
    std::cin >> n;
    std::cout << "Введіть початкове значення m: ";
    std::cin >> m;

    // Вираз 1: m - ++n (спочатку n збільшується на 1, потім виконується віднімання)
    int res1 = m - ++n;
    std::cout << "1) m - ++n = " << res1 << " (після операції: m = " << m << ", n = " << n << ")\n";

    // Вираз 2: ++m > --n (m збільшується на 1, n зменшується на 1, потім порівнюються)
    bool res2 = (++m > --n);
    std::cout << "2) ++m > --n = " << res2 << " (після операції: m = " << m << ", n = " << n << ")\n";

    // Вираз 3: --n < ++m (n зменшується на 1, m збільшується на 1, потім порівнюються)
    bool res3 = (--n < ++m);
    std::cout << "3) --n < ++m = " << res3 << " (після операції: m = " << m << ", n = " << n << ")\n";

    return 0;
}
