#include <iostream>
using namespace std;

int main() {
    int n; // Кількість елементів у першому масиві
    cin >> n;

    int* arr1 = new int[n]; // Динамічний масив для першої послідовності
    // Зчитування елементів першого масиву
    for (int i = 0; i < n; ++i) {
        cin >> arr1[i];
    }

    int m; // Кількість елементів у другому масиві
    cin >> m;

    int* arr2 = new int[m]; // Динамічний масив для другої послідовності
    // Зчитування елементів другого масиву
    for (int i = 0; i < m; ++i) {
        cin >> arr2[i];
    }

    int count1 = 0; // Лічильник спільних елементів

    // Пошук кількості спільних елементів у обох масивах
    for (int i = 0; i < n; ++i) {
        for (int j = 0; j < m; ++j) {
            if (arr1[i] == arr2[j]) {
                ++count1;
                break;
            }
        }
    }

    int count2 = n + m - count1; // Кількість унікальних елементів у обох масивах

    cout << count1 << endl;
    cout << count2;

    // Звільнення пам'яті
    delete[] arr1; 
    delete[] arr2;

    return 0;
}
