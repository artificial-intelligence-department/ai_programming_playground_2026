#include <iostream>
#include <cstring>
using namespace std;

int main() {
    // Буфер для зберігання рядка (до 255 символів + нуль-термінатор)
    char text[256];

    printf("Введіть рядок: ");
    // Безпечне зчитування рядка цілком (захист від переповнення буфера)
    fgets(text, 256, stdin);

    // Розділяємо рядок на слова; роздільниками є пробіли, крапка та перехід на новий рядок
    char* tmp = strtok(text, " .\n");

    // Перевірка випадку, коли рядок порожній або містить лише пробіли
    if (tmp == NULL) {
        printf("Слів не введено.\n");
        return 0;
    }

    // Довжина першого знайденого слова слугує початковим мінімумом
    size_t min_length = strlen(tmp);

    // Послідовно обробляємо всі інші слова у рядку
    while (tmp != NULL) {
        size_t len = strlen(tmp);

        // Якщо поточне слово коротше за поточний мінімум — оновлюємо його
        if (len < min_length) {
            min_length = len;
        }

        // Переходимо до наступного слова
        tmp = strtok(NULL, " .\n");
    }

    // Виведення результату
    printf("Довжина найкоротшого слова: %zu\n", min_length);
    return 0;
}
