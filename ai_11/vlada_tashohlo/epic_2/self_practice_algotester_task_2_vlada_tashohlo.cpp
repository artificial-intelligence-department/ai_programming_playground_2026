#include <cmath>
#include <iostream>

int main() {

    double a, b, c, r;
    std::cin >> a >> b >> c >> r; // Зчитуємо сторони трикутника та радіус кола.

    const double EPS = 1e-9; // Допуск на похибку обчислень з double.
    double p = (a + b + c) / 2.0; // Півпериметр трикутника.
    double s = std::sqrt(p * (p - a) * (p - b) * (p - c)); // Площа за Героном.
    double bigR = a * b * c / (4.0 * s); // Радіус описаного кола.
    double smallR = s / p; // Радіус вписаного кола.

    // Перевіряємо, чи вміщається трикутник у коло: описане коло трикутника не більше за задане коло.
    char first = (bigR <= r + EPS) ? '+' : '-';
    // Перевіряємо, чи вміщається коло в трикутник: задане коло не більше за вписане коло трикутника.
    char second = (r <= smallR + EPS) ? '+' : '-';

    std::cout << first << second << "\n"; // Виводимо результуючі два символи в одному рядку.

    return 0;
}
