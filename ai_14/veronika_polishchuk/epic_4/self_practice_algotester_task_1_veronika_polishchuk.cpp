#include <iostream>
#include <cmath>
using namespace std;

int main() {
    // Максимальний розмір матриці згідно з обмеженнями задачі
    const int N = 1000;
    
    int n, m, a[N][N];
    
    cin >> n >> m;
    
    for (int i = 0; i < n; i++){
        for (int j = 0; j < m; j++){
            cin >> a[i][j];
        }
    }

    // Початкове значення результату (1000 - максимально можливе число за умовою)
    long long result = 1000;
    
    // Проходимося по кожному стовпцю
    for (int j = 0; j < m; j++) {
        // Припускаємо, що перший елемент поточного стовпця є найбільшим
        int maxincol = a[0][j];

        // Шукаємо найбільше число у поточному стовпці (це число вибере Роман)
        for (int i = 0; i < n; i++) {
            if (a[i][j] > maxincol) {
                maxincol = a[i][j];
            }
        }
        
        // Віталік обирає стовпець так, щоб число Романа було мінімально можливим, 
        // тому шукаємо найменше серед усіх максимумів стовпців
        if (maxincol < result) {
            result = maxincol;
        }
    }
    cout << result;
    return 0;
}