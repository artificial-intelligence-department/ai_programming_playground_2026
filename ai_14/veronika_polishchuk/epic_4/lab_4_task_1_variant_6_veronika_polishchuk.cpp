#include <iostream>
#include <cstdlib>
#include <ctime>

using namespace std;

int main(){
    // Ініціалізація генератора випадкових чисел поточним часом для забезпечення випадковості послідовності
    srand(time(0));

    const int N = 100;

    int n = rand() % 100 + 1; // Генерація випадкового розміру масиву в межах від 1 до 100
    int a[N];
    int c, index = -1; // index ініціалізується значенням -1 як ознака відсутності знайденого елемента

    // Заповнення масиву випадковими числами у діапазоні від 1 до 200
    for (int i = 0; i < n; i++){
        a[i] = rand() % 200 + 1;
    }
    
    // Виведення початкового згенерованого масиву на екран
    cout << "Початковий масив: "; 
    for (int i = 0; i < n; i++) {
        cout << a[i] << " ";
    }
    cout << endl;
    
    // Отримання від користувача номера елемента, який необхідно видалити
    cout << "Введіть номер елемента для видалення ";
    cin >> c;

    c--; 
    
    // Перевірка коректності введеного індексу та видалення елемента шляхом зсуву елементів ліворуч
    if (c >= 0 && c < n){
        for (int i = c; i < n; i++){
            a[i] = a[i+1];
        }
        n--; // Зменшення фактичної кількості елементів масиву
    }

    // Пошук індексу першого парного елемента в оновленому масиві
    for (int i = 0; i < n; i++) {
        if (a[i] % 2 == 0) {
            index = i;
            break;
        }
    }
    
    if (index == -1) cout << "Немає парних чисел" << endl;
    
    // Розрахунок нового значення на основі попереднього елемента відносно знайденого парного
    int newValue = a[index - 1] + 2; 
    
    // Перевірка, чи знайдено парний елемент не на першій позиції, та вставка нового елемента праворуч від нього
    if (index > 0 ){
        for (int i = n; i > index + 1; i--){
            a[i] = a[i - 1]; // Зсув елементів праворуч для звільнення місця
        }
        n++;
        a[index + 1] = newValue; // Вставка нового значення у масив
    }
    else {
        cout << "Перший елемент масиву парний, неможливо додати елемент" << endl;
    }
    
    for (int i = 0; i < n; i++) {
        cout << a[i] << " ";
    }
    cout << endl;

    return 0;
}