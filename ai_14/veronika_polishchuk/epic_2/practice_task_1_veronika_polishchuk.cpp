#include <iostream>

using namespace std;

int main() {
    // Рівні надійності пароля для зручності використання в switch
    const int LVL_1 = 1;
    const int LVL_2 = 2;
    const int LVL_3 = 3;
    const int LVL_4 = 4;
    const int LVL_5 = 5;

    int length;
    char a, b, c;

    cout << "Довжина пароля: ";
    cin >> length;

    // Перевіряємо  межі поля введення, щоб уникнути від'ємних значень або переповнення
    if ( length < 1 || length > 64 ) {
        cout << "Помилка: довжина мусить бути від 1 до 64." << endl;
        return 0;
    }
    
    cout << "Чи є цифри (y/n): ";
    cin >> a;

    // Відсікаємо некоректне введення для подальших перевірок
    if (!(a == 'y' || a == 'n')) {
        cout << "Помилка: введіть дійсне значення(y/n)." << endl;
        return 0;
    }

    cout << "Чи є великі літери (y/n): ";
    cin >> b;

    if ( b != 'y' && b != 'n') {
        cout << "Помилка: введіть дійсне значення(y/n)." << endl;
        return 0;
    }

    cout << "Чи є спеціальні символи (y/n): ";
    cin >> c;

    if ( c != 'y' && c != 'n') {
        cout << "Помилка: введіть дійсне значення(y/n)." << endl;
        return 0;
    }

    // Рахуємо різноманітність символів, бо комбінація різних типів збільшує складність підбору
    int count = 0;
    if (a == 'y') count++;
    if (b == 'y') count++;
    if (c == 'y') count++;

    cout << "Мінімальні вимоги: ";
    // Базовий стандарт безпеки вимагає від 8 символів та принаймні 2 різних типів даних
    if (length >= 8 && count >= 2) { 
        cout << "ПРОЙДЕНО" << endl;
    } else {
        cout << "НЕ ПРОЙДЕНО" << endl;
    }

    // Змінна оголошена зовні розгалуження, щоб зберегти значення для блоку switch
    int level = 0;
    cout << "Рівень надіності: ";

    // Оцінюємо рівень 
    if (length < 6) {
        // Паролі коротші за 6 символів підбираються дуже швидко
        level = LVL_1;
        cout << level << " - Дуже слабкий" << endl;
    } 
    else if (length < 8 || count == 0) {
        // До 8 символів або без жодних додаткових типів теж легко дізнатися
        level = LVL_2;
        cout << level << " - Слабкий" << endl;
    }
    else if (count == 1) {
        // Лише один додатковий тип символів дає середній захист
        level = LVL_3;
        cout << level << " - Середній" << endl;
    }
    else if (length >= 12 && count == 3) {
        // Найвищий рівень надається тільки за максимальної довжини (12+) та використання усіх 3 типів
        level = LVL_5;
        cout << level << " - Дуже надійний" << endl;
    }
    else {
        // Усі інші комбінації, що відповідають гарним стандартам
        level = LVL_4;
        cout << level << " - Надійний" << endl;
    }

    cout << "Рекомендація: ";
    switch (level) {
        case LVL_1:
            cout << "Пароль надто короткий. Мінімум 8 символів." << endl;
            break;
        case LVL_2:
            cout << "Збільште довжину до 8+ символів і додайте цифри, великі літери або спеціальні символи." << endl;
            break;
        case LVL_3:
            cout << "Додайте ще один тип символів або збільште довжину до 12." << endl;
            break;
        case LVL_4:
            cout << "Хороший пароль. Для максимуму 12+ символів і всі три типи символів." << endl;
            break;
        case LVL_5:
            cout << "Відмінно. Змінювати нічого не потрібно." << endl;
            break;
        default:
            cout << "Невідомий рівень." << endl;
            break;
    }

    // Паролі тільки з букв дуже прості, тому виводиться попередження
    if ( count == 0 && length >= 4) {
        cout << "Попередження: пароль тільки з літер підбирається швидше." << endl;
    }

    return 0;
}