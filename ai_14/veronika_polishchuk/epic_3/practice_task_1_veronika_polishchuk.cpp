#include <iostream>
#include <iomanip>   // setw, setprecision: вирівнювання і формат чисел
#include <cmath>     // fabs: модуль числа (вимога для перевитрати)
using namespace std;

const int MAX_DAYS = 31;   // облік не довше місяця, тому масив на 31 елемент

// Пункт 1. Єдине місце, де масив обходиться циклом for лише для виводу
void showSpending(const double a[], int n){
    cout << "День     Витрати, грн\n";
    cout << fixed << setprecision(2);   // завжди 2 знаки після коми, як у прикладі
    for (int i = 0; i < n; i++) {
        // i + 1, бо дні нумеруються з 1, а індекси масиву з 0
        cout << setw(4) << i + 1 << setw(16) << a[i] << "\n";
    }
}

// mn і mx передаються за посиланням (&), тому функція змінює змінні з викликаючого
// коду. Так одна функція "повертає" два значення одразу
void minMax(const double a[], int n, double &mn, double &mx){
    // Початкові значення беремо з a[0], а не 0: інакше, якщо всі витрати
    // додатні, мінімум помилково лишився б нулем
    mn = a[0];
    mx = a[0];
    for (int i = 1; i < n; i++) {   // з 1, бо a[0] уже враховано
        if (a[i] < mn) mn = a[i];
        if (a[i] > mx) mx = a[i];
    }
}

// Рекурсія замість циклу (вимога задачі).
// Сума n елементів = останній елемент + сума попередніх n-1
double sumRecursive(const double a[], int n){
    if (n == 0) {   // базовий випадок: без нього функція викликала б себе безкінечно
        return 0;
    }
    return a[n-1] + sumRecursive(a, n-1);
}  

// Пункт 2. Збирає всі статистичні показники в одному місці
void showStats(const double a[], int n, double budget) {
    double mn, mx, average=0, day_average=0;   // average тут накопичує суму, а не середнє
    int count=0;                               // кількість днів з покупками
    minMax(a, n, mn, mx);
    double sum = sumRecursive(a, n);
    cout << fixed << setprecision(2);
    cout << "Мінімальні витрати за день: "<< setw(8)  << mn << " грн\n";
    cout << "Максимальні витрати за день: "<< setw(8)  << mx << " грн\n";
    cout << "Сумарні витрати: " << setw(8) << sum << " грн\n";

    // Або перевитрата, або залишок: показуємо щось одне залежно від суми
    if (sum > budget)
        // budget - sum тут від'ємне, fabs робить його додатним розміром перевитрати
        cout << "Перевитрата понад бюджет: " << setw(8) << fabs(budget - sum) << " грн\n";
    else
        cout << "Залишок бюджету: "<< setw(8)  << budget - sum << " грн\n";

    // Середнє рахуємо лише за дні з покупками, тому нулі пропускаємо через continue.
    // Якби ділили суму на n, нульові дні занижували б середнє
    for (int i = 0; i < n; i++) {
        if (a[i] == 0) continue;
        average += a[i];
        count++;
    }
    // Перевірка count > 0 захищає від ділення на нуль, коли всі дні без покупок
    if (count > 0) {
        day_average = average / count;
        cout << "Днів з покупками: "<< setw(8)  << count << "\n";
        cout << "Середні витрати за такий день: "<< setw(8)  << day_average << " грн\n";
    } 
    else {
        cout << "Днів з покупками немає\n";
    }

    // Накопичуємо витрати день за днем і зупиняємося на першому дні, де сума
    // перевищила бюджет. Умова i < n не дає вийти за межі масиву
    int i = 0;
    double acc = 0;
    while (i < n) {
        acc += a[i];
        if (acc > budget) break;   // перервати одразу, а не перебирати решту днів
        i++;
    }
    // Після циклу i показує, як він завершився: i < n означає, що спрацював break
    // (бюджет вичерпано), а i == n означає, що пройшли всі дні без перевищення
    if (i<n) cout<< "Бюджет вичерпано на дні "<<i+1<< ", накопичено " << acc << " грн"<< endl;
    else cout << "Бюджету вистачило на всі дні. Залишок: "<< budget-acc<<" грн" << endl;
}

// limit = 1000 це параметр за замовчуванням: якщо викликати overLimit(a, n)
// без третього аргумента, limit автоматично стане 1000
void overLimit(const double a[], int n, double limit = 1000){
    int count = 0;
    cout << fixed << setprecision(2);
    cout << "Ліміт: " << limit << " грн" << endl;

    for (int i = 0; i < n; i++) {
        if (a[i] > limit) {   // строго більше: день рівно на межі ліміту не рахується
            cout << "  день " << i + 1 << ": " << a[i] << " грн" << endl;
            count++;
        }
    }
    cout << "Разом днів з перевищенням: " << count << endl;
}

void topThree(const double a[], int n) {
    // Сортуємо копію b, щоб початковий масив a лишився без змін (вимога задачі)
    double b[MAX_DAYS];
    for (int i = 0; i < n; i++) {
        b[i] = a[i];
    }
    // Сортування вибором за спаданням: на місце i ставимо найбільше з решти
    for (int i = 0; i < n - 1; i++) {
        for (int j = i + 1; j < n; j++) {
            if (b[j] > b[i]) {
                // обмін через тимчасову змінну, інакше одне значення затреться
                double z = b[i];
                b[i] = b[j];
                b[j] = z;
            }
        }
    }
    // Якщо днів менше трьох, виводимо стільки, скільки є
    int count = (n < 3) ? n : 3;
    cout << fixed << setprecision(2);
    cout << "Топ-3 витрат: ";
    for (int i = 0; i < count; i++) {
        cout << b[i];
        if (i < count - 1) cout << ", ";   // кома між числами, але не після останнього
    }
    cout << " грн\n";
}

int main() {
    double budget;
    int n;
    double spending[MAX_DAYS];
    int choice;

    // Валідація кожного значення: якщо ввід некоректний, clear() скидає стан
    // помилки cin, а ignore() викидає зайві символи. Без цього цикл зациклився б
    cout << "Бюджет на місяць (грн): ";
    while (!(cin >> budget) || budget <= 0) {
        cin.clear();
        cin.ignore(10000, '\n');
        cout << "Помилка, бюджет має бути числом більше 0: ";
    }
    
    // Верхня межа MAX_DAYS захищає масив від переповнення
    cout << "Кількість днів обліку: ";
    while (!(cin >> n) || n < 1 || n > MAX_DAYS) {
        cin.clear();
        cin.ignore(10000, '\n');
        cout << "Помилка, введіть ціле число від 1 до 31: ";
    }
    
    // Нульові витрати дозволені (дні без покупок), заборонені тільки від'ємні
    cout << "Витрати по днях (грн): ";
    for (int i = 0; i < n; i++) {
        while (!(cin >> spending[i]) || spending[i] < 0) {
            cin.clear();
            cin.ignore(10000, '\n');
            cout << "Помилка, витрата дня " << i + 1 << " не може бути від'ємною. Введіть ще раз: ";
        }
    }

    // do while гарантує, що меню покажеться хоча б раз і повторюватиметься до виходу (0)
    do {
    menu:   // мітка для goto: сюди повертаємо користувача після помилки
        cout << "\n1 - Витрати по днях\n2 - Статистика\n"
                "3 - Дні з перевищенням ліміту\n4 - Три найдорожчі дні\n0 - Вийти\n";
        cout << "Ваш вибір: ";

        // Якщо ввели літери замість числа, потік у стані помилки, тому спершу чистимо його
        if (!(cin >> choice)) {
            cin.clear();
            cin.ignore(10000, '\n');
            cout << "Помилка вводу!\n";
            goto menu;
        }

        switch (choice) {
            case 1: showSpending(spending, n); break;
            case 2: showStats(spending, n, budget); break;
            case 3: {
                // Фігурні дужки потрібні, бо всередині case оголошується змінна
                double limit;
                cout << "Денний ліміт (грн, 0 = за замовчуванням): ";
                while (!(cin >> limit) || limit < 0) {
                    cin.clear();
                    cin.ignore(10000, '\n');
                    cout << "Помилка, введіть число не менше 0: ";
                }
                // 0 означає "взяти стандартний ліміт": викликаємо без третього аргумента,
                // тоді спрацьовує параметр за замовчуванням
                if (limit == 0) overLimit(spending, n);
                else overLimit(spending, n, limit);
                break;
            }
            case 4: topThree(spending, n); break;
            case 0: break;   // нічого не робимо, умова while (choice != 0) завершить цикл
            default:
                cout << "Невірний пункт!\n";
                goto menu;
        }
    } while (choice != 0);
    return 0;
}