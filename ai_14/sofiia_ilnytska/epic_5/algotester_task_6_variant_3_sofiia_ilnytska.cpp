#include <iostream>
using namespace std;
int main() {
    int n;
    cin >> n;

    //Кожен рядок зберігається як рядок символів-цифр.
    // 11 = до 10 символів + завершальний '\0'
    char g[10][11];
    for (int i = 0; i < n; i++) {
        cin >> g[i];
    }
    int q;
    cin >> q;
    while (q--) {
        int x, y;
        cin >> x >> y;  // координати клітинки (нумерація з 1)
        x--; y--;       // переходимо до індексів з 0

        // Якщо клітинка вже заповнена, єдиний варіант це її поточна цифра
        if (g[x][y] != '0') {
            cout << 1 << "\n" << g[x][y] << "\n";
            continue;   // переходимо до наступного запиту
        }

        // used[d] == true означає, що цифра d вже є в рядку або стовпці
        bool used[10] = {false};
        for (int j = 0; j < n; j++) used[g[x][j] - '0'] = true; // рядок
        for (int i = 0; i < n; i++) used[g[i][y] - '0'] = true; // стовпець

        // Збираємо цифри від 1 до n, яких немає ні в рядку, ні в стовпці
        int res[10];
        int m = 0;
        for (int d = 1; d <= n; d++){
            if (!used[d]) {
                res[m] = d;  // записуємо цифру в результат
                m++;
            }
        }

        cout << m << "\n";
            
        for (int i = 0; i < m; i++) {
            cout << res[i] << " ";
        }
        cout << "\n";
    }
    return 0;
}