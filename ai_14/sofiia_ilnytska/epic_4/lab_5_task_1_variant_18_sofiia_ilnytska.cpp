#include <iostream>
using namespace std;

// Максимально допустимий розмір матриці
const int MAX = 100;

// Виведення квадратної матриці
void printMatrix(int a[][MAX], int n) {
    // Послідовний обхід усіх рядків і стовпців
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            cout << a[i][j] << " ";
        }
        cout << endl;
    }
}

// Обмін двох рядків матриці
void swapRows(int a[][MAX], int n, int r1, int r2) {
    // Міняємо місцями відповідні елементи рядків
    for (int j = 0; j < n; j++) {
        int temp = a[r1][j];
        a[r1][j] = a[r2][j];
        a[r2][j] = temp;
    }
}

// Обмін двох стовпців матриці
void swapCols(int a[][MAX], int n, int c1, int c2) {
    // Міняємо місцями відповідні елементи стовпців
    for (int i = 0; i < n; i++) {
        int temp = a[i][c1];
        a[i][c1] = a[i][c2];
        a[i][c2] = temp;
    }
}

// Пошук максимальних елементів у квадратних підмасивах та їх переміщення на бічну діагональ
void arrangeMatrix(int a[][MAX], int n) {

    // k визначає поточний підмасив розміром (n-k) x (n-k)
    for (int k = 0; k < n; k++) {

        // Початково вважаємо максимальним нижній лівий елемент поточного підмасиву
        int maxRow = k;
        int maxCol = 0;

        // Пошук максимального елемента в підмасиві: рядки від k до n-1, стовпці від 0 до n-k-1
        for (int i = k; i < n; i++) {
            for (int j = 0; j < n - k; j++) {

                // Запам'ятовуємо координати нового максимуму
                if (a[i][j] > a[maxRow][maxCol]) {
                    maxRow = i;
                    maxCol = j;
                }
            }
        }

        // Переміщуємо рядок із максимумом на позицію k
        swapRows(a, n, k, maxRow);

        // Переміщуємо стовпець із максимумом у правий верхній кут поточного підмасиву
        swapCols(a, n, n - 1 - k, maxCol);
    }
}

// Перевірка строго спадної послідовності елементів бічної діагоналі
bool isDecreasing(int a[][MAX], int n) {

    // Порівнюємо кожен елемент діагоналі з наступним
    for (int i = 0; i < n - 1; i++) {

        // На бічній діагоналі індекс стовпця = n-1-i
        // Якщо наступний елемент не менший, спадання немає
        if (a[i][n - 1 - i] <= a[i + 1][n - 2 - i]) {
            return false;
        }
    }

    // Усі сусідні елементи розташовані за спаданням
    return true;
}

int main() {
    // Статичний двовимірний масив і його фактичний розмір
    int a[MAX][MAX];
    int n;

    cout << "Введіть розмір матриці: ";
    cin >> n;

    // Перевірка допустимого розміру матриці
    if (n < 1 || n > MAX) {
        cout << "Неправильний розмір матриці";
        return 0;
    }

    // Заповнення матриці значеннями користувача
    cout << "Введіть елементи матриці:" << endl;
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            cin >> a[i][j];
        }
    }

    // Виведення початкової матриці
    cout << "Початкова матриця:" << endl;
    printMatrix(a, n);

    // Пошук максимумів і перестановка рядків та стовпців
    arrangeMatrix(a, n);

    // Виведення матриці після перетворень
    cout << "Матриця після перестановок:" << endl;
    printMatrix(a, n);

    // Перевірка результату на бічній діагоналі
    if (isDecreasing(a, n)) {
        cout << "Бічна діагональ є спадною";
    } else {
        cout << "Бічна діагональ не є спадною";
    }

    return 0;
}

