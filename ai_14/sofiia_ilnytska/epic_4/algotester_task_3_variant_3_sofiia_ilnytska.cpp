#include <iostream>
#include <string>
using namespace std;

int main() {
    string tape;
    cin >> tape;  // Вводимо стрічку
    int count = 1;  // Зберігаємо кількість однакових символив поспіль
    for (int i = 0; i < tape.size(); i++) {
        if (tape[i] == tape[i + 1]) {  // Якщо наступний символ такий самий, продовжуємо рахувати повторення
            count++;
        } else if (tape[i] != tape[i + 1]) {  // Якщо символ змінився, завершуємо підрахунок попередньої групи
            if (count > 1) {  // Якщо символ повторювався, виводимо його разом із кількістю повторень
                cout << tape[i] << count;
            } else {  // Якщо символ зустрівся один раз, виводимо лише його
                cout << tape[i];
            }
            count = 1;  // Обнуляємо підрахунок повторень для наступної групи символів
        }
    }
    return 0;
}