#include <iostream>
#include <cstdlib>
#include <ctime>
using namespace std;

const int MAX = 100;  // Максимальна місткість масиву з урахуванням додавання двох елементів

void printRing(int a[], int n, int k) {   // Функція виведення однонаправленого кільця, починаючи з K-го елемента
    if (n == 0) {   // Перевірка, чи залишилися елементи в кільці
        cout << "Кільце порожнє" << endl;
        return;
    }

    int index = (k - 1) % n;  // Перетворення номера K на індекс масиву

    for (int i = 0; i < n; i++) {   // Повний обхід кільця з переходом від останнього елемента до першого
        cout << a[index] << " ";
        index = (index + 1) % n;
    }
    cout << endl;
}

int main() {
    srand(time(NULL));

    int a[MAX];
    int n, k;

    cout << "Введіть кількість елементів: ";
    cin >> n;

    if (n < 1 || n > MAX - 2) {   // Перевірка допустимої довжини з резервом для двох нових елементів
        cout << "Неправильна кількість елементів";
        return 0;
    }

    cout << "Введіть K: "; 
    cin >> k;

    if (k < 1 || k > n) {   // K має відповідати одному з номерів елементів початкового кільця
        cout << "Неправильне значення K";
        return 0;
    }

    for (int i = 0; i < n; i++) {  // Заповнення масиву випадковими числами від 0 до 99
        a[i] = rand() % 100;
    }

    cout << "Початкове кільце: ";  // Виведення початкового кільця від K-го до (K-1)-го елемента
    printRing(a, n, k);

    // Збереження першого та останнього елементів для подальшого копіювання
    int first = a[0];
    int last = a[n - 1];

    for (int i = n; i > 0; i--) {  // Зсув усіх елементів вправо для звільнення першої позиції
        a[i] = a[i - 1];
    }

    a[0] = first;  // Додавання копії першого елемента на початок масиву
    n++;

    a[n] = last;   // Додавання копії останнього елемента в кінець масиву
    n++;

    cout << "Кільце після додавання елементів: ";  // Виведення кільця після збільшення кількості елементів
    printRing(a, n, k);

    for (int i = 0; i < n; i++) {  // Послідовна перевірка всіх елементів на парність
        if (a[i] % 2 == 0) {
            for (int j = i; j < n - 1; j++) {  // Зсув наступних елементів вліво для видалення парного числа
                a[j] = a[j + 1];
            }
            n--;  // Зменшення реальної довжини масиву після видалення
            i--;  // Повторна перевірка позиції, на яку змістився наступний елемент
        } 
    }

    cout << "Кільце після видалення парних елементів: ";  // Виведення кільця після видалення всіх парних елементів
    printRing(a, n, k);

    return 0;
}