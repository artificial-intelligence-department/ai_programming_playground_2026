#include <iostream>
using namespace std;

int main() {
    long long n;
    cin >> n;  // Зчитуємо кількість чисел в масиві
    long long r[100000] = {0};  // Створюємо масив для збереження чисел
    for (int i = 0; i < n; i++) {
        cin >> r[i];  // Зчитуємо числа та записуємо їх у масив
    }

    for (int i = 0; i < n; i++) {  // Сортуємо числа за зростанням методом бульбашки
        for (int j = 0; j < n - 1; j++) {
            if (r[j + 1] < r[j]) {
                long long temporary;
                temporary = r[j];
                r[j] = r[j + 1];
                r[j + 1] = temporary;
            }
        }
    }

    if (n >= 2) {  // Якщо чисел 2 або більше, розглядаємо два можливі варіанти
        long long first = r[n-1] - r[1];  // Віднімаємо друге найменше число від найбільшого
        long long last = r[n-2] - r[0];   // Віднімаємо найменше число від другого найбільшого
        if (first > last) {   // Виводимо менший із двох отриманих результатів
            cout << last;
        } else if (first < last) {
            cout << first;
        } else if (first == last) {  // Якщо результати однакові, можна вивести будь-яке
            cout << first; 
        }
    } else if (n == 1) { // Якщо є лише одне число, результат дорівнює 0
        cout << 0;
    }
    return 0;
}