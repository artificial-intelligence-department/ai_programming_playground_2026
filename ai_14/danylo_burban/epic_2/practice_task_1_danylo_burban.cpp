#include <iostream>

using namespace std;

int main(){
    int length;
    string isDigit;
    string isCapital;
    string isSpecial;

    int unique = 0; // Кількість присутніх типів символів (цифри, великі літери, спецсимволи)
    int level = 0;  // Оцінка надійності за шкалою від 1 до 5

    // --- Введення та валідація даних ---
    cout << "Довжина пароля: ";
    if ((!(cin >> length)) || length < 1 || length > 64) {
        cout << "Введіть коректну довжину пароля";
        return 1;
    }

    // Зчитування наявності різних типів символів та підрахунок їх кількості
    cout << "Чи є цифри (y/n) ";
    if ((!(cin >> isDigit)) || (isDigit != "y" && isDigit != "n")) {
        cout << "Введіть коректне значення";
        return 1;
    } else if (isDigit == "y") {
        unique++;
    }

    cout << "Чи є великі літери (y/n) ";
    if ((!(cin >> isCapital)) || (isCapital != "y" && isCapital != "n")) {
        cout << "Введіть коректне значення";
        return 1;
    } else if (isCapital == "y") {
        unique++;
    }

    cout << "Чи є спеціальні символи (y/n) ";
    if ((!(cin >> isSpecial)) || (isSpecial != "y" && isSpecial != "n")) {
        cout << "Введіть коректне значення";
        return 1;
    } else if (isSpecial == "y") {
        unique++;
    }

    // --- Перевірка відповідності мінімальним вимогам ---
    // Поточна логіка: вимагає довжину від 8 символів та наявність усіх 3 додаткових типів
    if (length < 8 || unique <= 2) {
        cout << "Мінімальні вимоги: НЕ ПРОЙДЕНО" << endl;
    } else {
        cout << "Мінімальні вимоги: ПРОЙДЕНО" << endl;
    }

    // --- Розрахунок рівня надійності пароля ---
    if (length < 6) {
        level = 1; // Дуже слабкий через критично малу довжину
    } else if (length < 8 || unique == 0) {
        level = 2; // Слабкий: короткий або складається лише з малих літер
    } else if (unique == 1) {
        level = 3; // Середній: достатня довжина та один додатковий тип символів
    } else if (length >= 12 || unique == 3) {
        level = 5; // Дуже надійний: довгий або містить усі типи символів
    } else {
        level = 4; // Надійний пароль
    }

    // --- Виведення результату та рекомендацій ---
    switch (level)
    {
    case 1:
        cout << "Рівень надійності: 1 - Дуже слабкий" << endl;
        cout << "Пароль надто короткий. Мінімум 8 символів." << endl;
        break;
    case 2:
        cout << "Рівень надійності: 2 - Слабкий" << endl;
        cout << "Збільште довжину до 8+ символів і додайте цифри, великі літери або спеціальні символи" << endl;
        break;
    case 3:
        cout << "Рівень надійності: 3 - Середній" << endl;
        cout << "Додайте ще один тип символів або збільште довжину до 12." << endl;
        break;
    case 4:
        cout << "Рівень надійності: 4 - Надійний" << endl;
        cout << "Хороший пароль. Для максимуму 12+ символів і всі три типи символів." << endl;
        break;
    case 5:
        cout << "Рівень надійності: 5 - Дуже надійний" << endl;
        cout << "Відмінно. Змінювати нічого не потрібно." << endl;
        break;
    default:
        cout << "Виникла невідома помилка" << endl;
        break;
    }

    // Додаткова перевірка для паролів, що складаються тільки з літер нижнього регістру
    if (unique == 0) {
        cout << "Попередження: пароль тільки з літер підбирається швидше." << endl;
    }

    return 0;
}