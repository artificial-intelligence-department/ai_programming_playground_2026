#include <iostream>
using namespace std;

int main(){

    int len, level, types = 0; // довжина пароля, рівень надійності, кількість типів символів
    string numbers, U_sym, sp_sym = ""; // чи є цифри, чи є великі літери, чи є спеціальні символи

    //Ввід всіх даних і їх перевірка
    cout << "Довжина пароля: ";
    if(cin >> len && len > 0 && len < 65){
    }else{
        cout << "Помилка: довжина мусить бути від 1 до 64.";
        return 1;
    }
    cout << "Чи є цифри (y/n): ";
    if(cin >> numbers && (numbers == "y" || numbers == "n")){
        if (numbers == "y"){types += 1;}
    }else{
        cout << "Помилка: введіть y або n";
        return 1;
    }
    cout << "Чи є великі літери (y/n): ";
    if(cin >> U_sym && (U_sym == "y" || U_sym == "n")){
        if (U_sym == "y"){types += 1;}
    }else{
        cout << "Помилка: введіть y або n";
        return 1;
    }
    cout << "Чи є спеціальні символи (y/n): ";
    if(cin >> sp_sym && (sp_sym == "y" || sp_sym == "n")){
        if (sp_sym == "y"){types += 1;}
    }else{
        cout << "Помилка: введіть y або n";
        return 1;
    }

    //Визначення, чи пароль проходить мінімальні вимоги

    if (len < 8 || types < 2){
        cout << "Мінімальні вимоги: НЕ ПРОЙДЕНО" << endl;
    }else{
        cout << "Мінімальні вимоги: ПРОЙДЕНО" << endl;
    }

    //Визначення рівня надійності пароля

    if (len < 6){
        level = 1;
        cout << "Рівень надійності: 1 - Дуже слабкий" << endl;
    }else if(len < 8 || types == 0){
        level = 2;
        cout << "Рівень надійності: 2 - Слабкий" << endl;
    }else if(types == 1){
        level = 3;
        cout << "Рівень надійності: 3 - Середній" << endl;
    }else if(len >= 12 && types == 3){
        level = 5;
        cout << "Рівень надійності: 5 - Дуже надійний" << endl;
    }else{
        level = 4;
        cout << "Рівень надійності: 4 - Надійний" << endl;
    }

    //Виведення рекомендацій
    
    switch(level){
        case 1: {
            cout << "Рекомендації: пароль надто короткий. Мінімум 8 символів." << endl;
            break;
        }
        case 2: {
            cout << "Рекомендації: збільште довжину до 8+ символів і додайте цифри, великі літери або спеціальні символи." << endl;
            break;
        }
        case 3: {
            cout << "Рекомендації: додайте ще один тип символів або збільште довжину до 12." << endl;
            break;
        }
        case 4: {cout << "Рекомендації: хороший пароль. Для максимуму 12+ символів і всі три типи символів." << endl;
            break;
        }
        case 5: {
            cout << "Рекомендації: відмінно. Змінювати нічого не потрібно." << endl;
            break;}
        default: {
            cout << "Виникла невідома помилка." << endl;
            return 1;
            break;}
    }

    //Виведення попередження, якщо це треба

    if(numbers == "n" && sp_sym == "n") {
    cout << "Попередження: пароль тільки з літер підбирається швидше." << endl;
}
    return 0;
}