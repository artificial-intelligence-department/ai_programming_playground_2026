#include <iostream>
#include <cmath> // Для pow та log

using namespace std;

int main() {
    double sum = 0.0; // Змінна для накопичення суми членів ряду
    int start_n = 2; // Починаємо з n = 2, оскільки ln(1) = 0, що призвело б до ділення на 0
    int num_terms = 15; // Кількість членів ряду, яку необхідно додати

    for (int i = 0; i < num_terms; ++i) {
        int n = start_n + i; // Поточне значення n для обчислення (від 2 до 16 включно)

        // Обчислюємо чисельник: n підносимо до степеня ln(n)
        double numerator = pow(n, log(n));

        // Обчислюємо знаменник: ln(n) підносимо до степеня n
        double denominator = pow(log(n), n);

        // Обчислюємо поточний член ряду та додаємо його до загальної суми
        sum += numerator / denominator;
    }

    // Налаштовуємо виведення чисел з плаваючою крапкою (10 знаків після коми)
    cout.precision(10);
    
    // Виводимо заголовок та результат
    cout << "Результат обчислення суми елементів:" << endl;
    cout << "Для ряду з загальним членом a_n = n^(ln(n)) / (ln(n))^n:" << endl;
    cout << "Сума перших " << num_terms << " членів ряду дорівнює: " << sum << endl;

    return 0; // Успішне завершення програми
}
