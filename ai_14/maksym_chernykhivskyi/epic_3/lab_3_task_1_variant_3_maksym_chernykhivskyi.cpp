#include <iostream>
#include <cmath>
#include <iomanip>

using namespace std;

// Функція для обчислення суми ряду за заданою кількістю членів n
double sum_by_n(double x, int n) {
    double sum = x;  // Перший член ряду дорівнює x
    double term = x; // Змінна для збереження поточного члена ряду
    
    // Послідовно обчислюємо та додаємо наступні n членів ряду
    for (int i = 1; i <= n; ++i) {
        // Рекурентне обчислення Тейлора: множимо попередній term на (-x^2) / (2i * (2i + 1)), 
        // що послідовно формує степені та факторіали: x -> -x^3/3! -> x^5/5! -> ...
        term *= -x * x / ((2 * i) * (2 * i + 1));
        sum += term; // Додаємо поточний член до загальної суми
    }
    return sum;
}

// Функція для обчислення суми ряду із заданою точністю eps
double sum_by_eps(double x, double eps) {
    double sum = x;  // Перший член ряду дорівнює x
    double term = x; // Поточний член ряду
    int i = 1;       // Індекс для рекурентного перерахунку
    
    while (true) {
        // Обчислюємо наступний член ряду
        term *= -x * x / ((2 * i) * (2 * i + 1));
        
        // Якщо модуль чергового члена став меншим за точність, зупиняємо цикл
        if (abs(term) < eps) {
            break;
        }
        
        sum += term; // Додаємо член ряду до суми, якщо він більший або рівний eps
        i++;         // Переходимо до наступного кроку
    }
    return sum;
}

int main() {
    double a = 0.1; // Початок діапазону зміни аргументу x
    double b = 1.0; // Кінець діапазону зміни аргументу x
    int k = 10; // Кількість кроків (відрізків) розбиття
    double h = (b - a) / k; // Крок зміни x
    int n = 10; // Задана кількість членів ряду
    double eps = 0.0001; // Задана точність

    // Виведення шапки таблиці результатів
    cout << setw(6) << "x" 
         << setw(25) << "Sin(x) точне" 
         << setw(25) << "Ряд (за n)" 
         << setw(25) << "Ряд (за eps)\n" << endl;

    // Форматування виведення чисел: фіксована крапка та 5 знаків після коми
    cout << fixed << setprecision(5);

    for (int step = 0; step <= k; ++step) {
        double x = a + step * h;
        
        double exact = sin(x);        // Точне значення,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,,....
        double s_n = sum_by_n(x, n);    // Значення суми для фіксованого n
        double s_eps = sum_by_eps(x, eps); // Значение суми для заданої точності eps

        // Виводимо рядок таблиці з результатами
        cout << setw(9) << x 
             << setw(15) << exact 
             << setw(21) << s_n 
             << setw(18) << s_eps << endl;
    }

    return 0;
}